package composegen_test

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/mixofreality-studio/archistrator-platform/framework-go-app-generator/composegen"
)

// The arrange endpoint (Plan 3 Task 3.5) is local-only by construction: the composition root mounts
// /__scenariohost/ only when the generated Config yields a scenario host address, and the Config
// rule that yields it refuses the variable under any other profile (configgen's
// TestConfig_LocalScenariohostURL). The forwarder is POST-only, with a short timeout, and strips its
// prefix so the scenario host's arrange server sees /<kind>.
func TestArrangeEndpoint_LocalOnly(t *testing.T) {
	got, err := composegen.Generate(loadGreenfield(t), greenfieldCfg)
	if err != nil {
		t.Fatal(err)
	}
	main := string(got[composegen.MainFile])
	for _, want := range []string{
		"scenariohostURL, err := cfg.LocalScenariohostURL(hooks.ResolveProfile(cfg))",
		"if scenariohostURL != \"\" {",
		`root.Handle("/__scenariohost/", arrangeForwarder(scenariohostURL))`,
	} {
		if !strings.Contains(main, want) {
			t.Errorf("main.gen.go lacks %q:\n%s", want, main)
		}
	}
	if i, j := strings.Index(main, `if scenariohostURL != ""`), strings.Index(main, `root.Handle("/__scenariohost/"`); i < 0 || j < i {
		t.Errorf("the mount is not inside the scenariohostURL guard (guard at %d, mount at %d)", i, j)
	}

	fwd, ok := got[composegen.ArrangeFile]
	if !ok {
		t.Fatalf("no %s generated", composegen.ArrangeFile)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), composegen.ArrangeFile, fwd, parser.AllErrors); err != nil {
		t.Fatalf("does not parse: %v\n%s", err, fwd)
	}
	for _, want := range []string{
		"// Code generated by composegen. DO NOT EDIT.",
		"func arrangeForwarder(target string) http.Handler",
		"http.MethodPost",
		"http.StatusMethodNotAllowed",
		`"/__scenariohost"`,
		"arrangeTimeout",
	} {
		if !strings.Contains(string(fwd), want) {
			t.Errorf("%s lacks %q:\n%s", composegen.ArrangeFile, want, fwd)
		}
	}
}
