// isBuiltNonClient reports a contract scenariocompose gives a constructor.
func isBuiltNonClient(c *projectmodel.Contract) bool {
	return c.Doc != nil && c.GoPackage != "" && !strings.EqualFold(c.Layer, "client")
}

// TestScenarioCompose_EveryContractHasConstructor: every built non-client contract gets a
// New<Iface>(t, h) constructor and a Null<Iface> wrapper; a client contract gets neither; the
// file registers every Manager's workflows; and nothing in it asks the app for anything (no
// hooks, no config, no FILL).
func TestScenarioCompose_EveryContractHasConstructor(t *testing.T) {
	m, _ := loadConformance(t, "todomvc")
	src, _, err := composegen.EmitScenarioCompose(m, scenarioCfg)
	if err != nil {
		t.Fatalf("EmitScenarioCompose: %v", err)
	}
	if _, err := parser.ParseFile(token.NewFileSet(), "compose.gen.go", src, parser.AllErrors); err != nil {
		t.Fatalf("does not parse: %v\n%s", err, src)
	}
	if formatted, err := format.Source(src); err != nil || string(formatted) != string(src) {
		t.Errorf("compose.gen.go is not gofmt-clean (err=%v)", err)
	}
	s := string(src)
	if !strings.HasPrefix(s, "// Code generated by composegen. DO NOT EDIT.\n") {
		t.Errorf("missing the generated header:\n%.200s", s)
	}
	if !strings.Contains(s, "\npackage scenariocompose\n") {
		t.Errorf("package clause is not scenariocompose")
	}

	built := 0
	for key, c := range m.Contracts {
		iface := c.Doc.Interface.Name
		ctor := regexp.MustCompile(`(?m)^func New` + iface + `\(t \*testing\.T, h \*scenariohost\.Host\) \w+\.` + iface + ` \{$`)
		null := regexp.MustCompile(`(?m)^func Null` + iface + `\(inner \w+\.` + iface + `, ops \.\.\.string\) \w+\.` + iface + ` \{$`)
		if !isBuiltNonClient(c) {
			if strings.Contains(s, "Null"+iface+"(") {
				t.Errorf("%s: a client/package-less contract must get no Null wrapper", key)
			}
			handlerCtor := regexp.MustCompile(`(?m)^func New` + iface + `\(t \*testing\.T, h \*scenariohost\.Host\) \*\w+\.Handler \{$`)
			wantHandler := strings.EqualFold(c.Layer, "client") && c.GoPackage != ""
			if wantHandler != handlerCtor.MatchString(s) {
				t.Errorf("%s: a client with a generated handler package gets `func New%s(t, h) *<pkg>.Handler` and a package-less one none (want constructor: %v)", key, iface, wantHandler)
			}
			continue
		}
		built++
		if !ctor.MatchString(s) {
			t.Errorf("%s: no `func New%s(t *testing.T, h *scenariohost.Host) <pkg>.%s`", key, iface, iface)
		}
		if !null.MatchString(s) {
			t.Errorf("%s: no `func Null%s(inner, ops ...string)` wrapper", key, iface)
		}
		if strings.EqualFold(c.Layer, "manager") && len(c.Deps) > 0 && !strings.Contains(s, "RegisterManagerWorker") {
			t.Errorf("%s: Workflows() must register the manager's workflows", key)
		}
	}
	if built == 0 {
		t.Fatal("the fixture has no built non-client contract; the test proves nothing")
	}
	for _, banned := range []string{"hooks.", "cfg.", "FILL", "permitAll"} {
		if strings.Contains(s, banned) {
			t.Errorf("compose.gen.go must not depend on the app's hand code: contains %q", banned)
		}
	}
	if !strings.Contains(s, "func Workflows() scenariohost.Workflows {") {
		t.Errorf("no Workflows() for the replay gate")
	}
}

// TestScenarioCompose_WorkflowsBuildPureDependencies: a Manager's workflow code calls its Engines in
// process, so a replay of its history executes them. Workflows() therefore builds every pure
// dependency (an Engine takes no substrate) for real; only what a workflow reaches through an
// activity (ResourceAccess, Utility, the Temporal client) is nil.
func TestScenarioCompose_WorkflowsBuildPureDependencies(t *testing.T) {
	m, _ := loadConformance(t, "todomvc")
	src, _, err := composegen.EmitScenarioCompose(m, scenarioCfg)
	if err != nil {
		t.Fatalf("EmitScenarioCompose: %v", err)
	}
	s := string(src)
	start := strings.Index(s, "func Workflows() scenariohost.Workflows {")
	if start < 0 {
		t.Fatal("no Workflows()")
	}
	body := s[start:]
	if end := strings.Index(body, "\n}\n"); end >= 0 {
		body = body[:end]
	}
	want := "list.RegisterManagerWorker(w, list.NewListManager(nil, messagebus.NewMessageBus(), accessgranting.NewAccessGrantingEngine(), listruling.NewListRulingEngine(), nil))"
	if !strings.Contains(body, want) {
		t.Errorf("Workflows() must build the Engines and nil the rest; want %q in\n%s", want, body)
	}
}

// TestScenarioCompose_ClientConstructorHasRealPolicy: each MCP and REST client contract of the todomvc
// fixture gets a New<ClientIface> returning its generated Handler over the real Manager, authorized
// by a policy built from the generated authorization rows - never a permit-all one.
func TestScenarioCompose_ClientConstructorHasRealPolicy(t *testing.T) {
	m, _ := loadConformance(t, "todomvc")
	src, _, err := composegen.EmitScenarioCompose(m, scenarioCfg)
	if err != nil {
		t.Fatalf("EmitScenarioCompose: %v", err)
	}
	s := string(src)
	for _, want := range []string{
		"func NewTodoMcpServerList(t *testing.T, h *scenariohost.Host) *todomcpserverlistclient.Handler {",
		"func NewTodoApiList(t *testing.T, h *scenariohost.Host) *weblistclient.Handler {",
		"&todomcpserverlistclient.Handler{Manager: buildListManager(subjectFor(t, h)), Security: edgeSecurity()}",
		"&weblistclient.Handler{Manager: buildListManager(subjectFor(t, h)), Security: edgeSecurity()}",
		"security.New(security.WithPolicyDecisionPoint(generatedPolicy{}))",
		"generatedAuthorizations[authzKey{verb: a.Verb, scope: r.Kind}]",
		"r.ID == p.Subject",
		`"github.com/mixofreality-studio/archistrator-platform/framework-go/utilities/security"`,
	} {
		if !strings.Contains(s, want) {
			t.Errorf("compose.gen.go lacks %q", want)
		}
	}
	if strings.Count(s, "{verb: \"") == 0 {
		t.Error("the policy table holds no generated authorization rows")
	}
	for _, banned := range []string{"permitAll", "return true, nil", "Security: nil", "PolicyDecisionPoint()"} {
		if strings.Contains(s, banned) {
			t.Errorf("the client policy must be deny-by-default and generated: contains %q", banned)
		}
	}
}

