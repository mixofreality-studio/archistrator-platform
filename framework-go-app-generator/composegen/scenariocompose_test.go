// TestScenarioCompose_CompilesAgainstScenariohost drives the REAL generator chain over the todomvc
// conformance fixture in a throwaway module wired to this checkout's platform modules (the
// real scenariohost, framework-go and Temporal SDK), adds the emitted compose.gen.go, and
// proves the whole module builds and vets - then runs the Null wrapper's behaviour.
func TestScenarioCompose_CompilesAgainstScenariohost(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping the compile sandbox in -short")
	}
	m, raw := loadConformance(t, "todomvc")
	out, err := nullgen.Emit(raw, nullgen.Options{ModulePath: scenarioCfg.ModulePath})
	if err != nil {
		t.Fatalf("nullgen.Emit: %v", err)
	}
	genDir, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	dir := t.TempDir()
	scaffoldScenarioSandbox(t, dir, genDir, raw, m)
	for path, src := range out.Files {
		writeSandboxFile(t, filepath.Join(dir, path), src)
	}
	bin := buildSandboxGenerators(t, genDir)
	project := filepath.Join(dir, ".aiarch", "state", "project.json")
	for _, args := range [][]string{
		{"modelgen", "-project", project, "-root", dir},
		{"appgen", "temporal", "-project", project, "-root", dir},
		{"appgen", "config", "-project", project, "-root", dir},
		{"appgen", "compose", "-project", project, "-root", dir},
		{"appgen", "clients", "-project", project, "-root", dir},
	} {
		runSandbox(t, dir, filepath.Join(bin, args[0]), args[1:]...)
	}

	src, _, err := composegen.EmitScenarioCompose(m, scenarioCfg)
	if err != nil {
		t.Fatalf("EmitScenarioCompose: %v", err)
	}
	writeSandboxFile(t, filepath.Join(dir, filepath.FromSlash(composegen.ScenarioComposeFile)), src)
	writeSandboxFile(t, filepath.Join(dir, "internal", "scenariocompose", "null_behaviour_test.go"), []byte(nullBehaviourTest))

	runSandbox(t, dir, "go", "build", "./...")
	runSandbox(t, dir, "go", "vet", "./...")
	runSandbox(t, dir, "go", "test", "-run", "TestNullWrapper", "./internal/scenariocompose")
}

// nullBehaviourTest runs inside the sandbox's scenariocompose package. It calls the wrapper's
// methods by reflection with zero arguments, so it needs no knowledge of the fixture's types:
// a named op returns without touching the (nil) inner subject; an unnamed op delegates to it
// (a nil-interface panic is the proof of delegation); an unknown op name panics.
const nullBehaviourTest = `package scenariocompose

import (
	"reflect"
	"testing"

	"example.com/todomvc/internal/engine/listruling"
)

func callWithZeroArgs(t *testing.T, subject any, op string) (panicked bool) {
	t.Helper()
	m := reflect.ValueOf(subject).MethodByName(op)
	if !m.IsValid() {
		t.Fatalf("no method %s on %T", op, subject)
	}
	args := make([]reflect.Value, m.Type().NumIn())
	for i := range args {
		args[i] = reflect.Zero(m.Type().In(i))
	}
	defer func() { panicked = recover() != nil }()
	m.Call(args)
	return false
}

func TestNullWrapper(t *testing.T) {
	var inner listruling.ListRulingEngine // nil: reaching it panics
	w := NullListRulingEngine(inner, "ListRulingEngine.JudgeTitle", "SomeOtherInterface.Whatever")
	if callWithZeroArgs(t, w, "JudgeTitle") {
		t.Error("a nulled op must return its zero result without calling the inner subject")
	}
	if !callWithZeroArgs(t, w, "TallyItemsLeft") {
		t.Error("an op that is not nulled must delegate to the inner subject")
	}
	none := NullListRulingEngine(inner)
	if !callWithZeroArgs(t, none, "JudgeTitle") {
		t.Error("with no ops named the wrapper is transparent")
	}
	defer func() {
		if recover() == nil {
			t.Error("naming an op the interface does not have must panic: a typo would stub nothing")
		}
	}()
	NullListRulingEngine(inner, "ListRulingEngine.NoSuchOp")
}
`

func scaffoldScenarioSandbox(t *testing.T, dir, genDir string, raw []byte, m *projectmodel.Model) {
	t.Helper()
	platform := filepath.Dir(genDir)
	const prefix = "github.com/mixofreality-studio/archistrator-platform/"
	replaces := []string{"framework-go", "framework-go-app-generator", "framework-go-http-generator",
		"framework-go-mcp-generator", "framework-go-projectmodel", "framework-go-infrastructure-github",
		"framework-go-infrastructure-keycloak", "framework-go-infrastructure-llm", "framework-go-infrastructure-otel",
		"framework-go-infrastructure-postgres", "framework-go-infrastructure-temporal", "framework-go-scenariohost"}
	var mod strings.Builder
	mod.WriteString("module " + scenarioCfg.ModulePath + "\n\ngo 1.25.0\n\nrequire (\n")
	for _, r := range replaces {
		mod.WriteString("\t" + prefix + r + " v0.0.0\n")
	}
	mod.WriteString(")\n\n")
	for _, r := range replaces {
		mod.WriteString("replace " + prefix + r + " => " + filepath.Join(platform, r) + "\n")
	}
	writeSandboxFile(t, filepath.Join(dir, "go.mod"), []byte(mod.String()))
	if sum, err := os.ReadFile(filepath.Join(genDir, "go.sum")); err == nil {
		writeSandboxFile(t, filepath.Join(dir, "go.sum"), sum)
	}
	writeSandboxFile(t, filepath.Join(dir, ".aiarch", "state", "project.json"), raw)
	for _, c := range m.Contracts {
		if c.GoPackage != "" {
			writeSandboxFile(t, filepath.Join(dir, c.GoPackage, "doc.go"), []byte("package "+filepath.Base(c.GoPackage)+"\n"))
		}
	}
}

func writeSandboxFile(t *testing.T, path string, src []byte) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		t.Fatal(err)
	}
}

func buildSandboxGenerators(t *testing.T, genDir string) string {
	t.Helper()
	bin := t.TempDir()
	cmd := exec.Command("go", "build", "-o", bin+string(filepath.Separator), "./cmd/modelgen", "./cmd/appgen")
	cmd.Dir = genDir
	cmd.Env = append(os.Environ(), "GOWORK=off")
	if o, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("building the generators: %v\n%s", err, o)
	}
	return bin
}

func runSandbox(t *testing.T, dir, name string, args ...string) {
	t.Helper()
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
	if o, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%s %v: %v\n%s", filepath.Base(name), args, err, o)
	}
}

// TestScenarioCompose_RefusalCascadesToDependentManagers: a Manager that depends on a refused
// Manager cannot be built either, and is named with the refused one as its dependency.
func TestScenarioCompose_RefusalCascadesToDependentManagers(t *testing.T) {
	m, _ := loadConformance(t, "greenfield")
	fm := m.Contracts["fulfillmentManager"]
	fm.Deps = append(fm.Deps, projectmodel.Dep{Name: "orders", Component: "orderManager"})
	src, refused, err := composegen.EmitScenarioCompose(m, composegen.Config{ContainerKey: "order-app", ModulePath: "example.com/greenfield/server"})
	if err != nil {
		t.Fatalf("EmitScenarioCompose: %v", err)
	}
	got := map[string]string{}
	for _, r := range refused {
		got[r.Manager] = r.Dependency
	}
	if got["fulfillmentManager"] != "orders" || got["orderManager"] == "" {
		t.Errorf("want orderManager refused and fulfillmentManager refused through orders, got %v", refused)
	}
	if strings.Contains(string(src), "NewFulfillmentManager") {
		t.Error("a Manager depending on a refused Manager must be left unbuilt")
	}
}

