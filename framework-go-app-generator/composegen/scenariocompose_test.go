// scenarioCfg is the invocation the scenariocompose tests share. The container is the one the
// default deployment names; the module path is the todomvc conformance fixture's.
var scenarioCfg = composegen.Config{ContainerKey: "server", ModulePath: "example.com/todomvc"}

// loadConformance loads a conformance fixture and gives it the deployment appgen would compose
// it with (the authored one, else the default), the model composegen is handed.
func loadConformance(t *testing.T, name string) (*projectmodel.Model, []byte) {
	t.Helper()
	raw, err := conformance.Fixture(name)
	if err != nil {
		t.Fatalf("fixture %q: %v", name, err)
	}
	m, err := projectmodel.Load(raw)
	if err != nil {
		t.Fatalf("load %q: %v", name, err)
	}
	effective := *m
	effective.Deployment = m.EffectiveDeployment(scenarioCfg.ContainerKey)
	return &effective, raw
}

