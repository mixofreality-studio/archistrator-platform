package composegen_test

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/mixofreality-studio/archistrator-platform/framework-go-app-generator/composegen"
)

// A container with web-exposed Managers gets null.gen.go beside main.gen.go: the null-op
// middleware the discrimination run (testgen -discriminate) exports AIARCH_NULL_OPS to. It wraps
// each web-exposed Manager in its Null wrapper, so the generated REST handlers and MCP tools answer
// a named operation with its zero result and never reach the Manager, and the composition root
// installs it through one call.
func TestNullMiddleware_EmittedForWebExposedManagers(t *testing.T) {
	got, err := composegen.Generate(loadGreenfield(t), greenfieldCfg)
	if err != nil {
		t.Fatal(err)
	}
	null, ok := got[composegen.NullFile]
	if !ok {
		t.Fatalf("no %s generated; have %d files", composegen.NullFile, len(got))
	}
	if _, err := parser.ParseFile(token.NewFileSet(), composegen.NullFile, null, parser.AllErrors); err != nil {
		t.Fatalf("does not parse: %v\n%s", err, null)
	}
	src := string(null)
	for _, want := range []string{
		"// Code generated by composegen. DO NOT EDIT.",
		"package main",
		`os.Getenv("AIARCH_NULL_OPS")`,
		"func applyNullOps(profile string, managers WebManagers) (WebManagers, error)",
		"func NullOrderManager(inner order.OrderManager, ops ...string) order.OrderManager",
		"managers.OrderManager = NullOrderManager(managers.OrderManager, ops...)",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %q in\n%s", want, src)
		}
	}
	if main := string(got[composegen.MainFile]); !strings.Contains(main, "webManagers, err = applyNullOps(hooks.ResolveProfile(cfg), webManagers)") {
		t.Errorf("the composition root does not install the null-op wrapper:\n%s", main)
	}
}

// The middleware is a test instrument: a process that boots with AIARCH_NULL_OPS under any profile
// but local refuses to start, so a production binary cannot be told to stub out its own operations.
func TestNullMiddleware_LocalOnly(t *testing.T) {
	got, err := composegen.Generate(loadGreenfield(t), greenfieldCfg)
	if err != nil {
		t.Fatal(err)
	}
	src := string(got[composegen.NullFile])
	for _, want := range []string{
		`profile != "local"`,
		"AIARCH_NULL_OPS is set under profile %q",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %q in\n%s", want, src)
		}
	}
}
