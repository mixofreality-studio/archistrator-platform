package composegen_test

import (
	"go/parser"
	"go/token"
	"strings"
	"testing"

	"github.com/mixofreality-studio/archistrator-platform/framework-go-app-generator/composegen"
)

// faults.gen.go (Plan 3 Task 3.5) wraps every web-exposed Manager so a scenario's failNext reaches
// the booted server: each operation asks take(<contract key>, <Op>) before calling the Manager, and
// answers the registered error code with the Manager error kind of that code.
func TestFaults_WrapEveryWebManagerOp(t *testing.T) {
	m := loadGreenfield(t)
	got, err := composegen.Generate(m, greenfieldCfg)
	if err != nil {
		t.Fatal(err)
	}
	src, ok := got[composegen.FaultsFile]
	if !ok {
		t.Fatalf("no %s generated; have %v", composegen.FaultsFile, keysOf(got))
	}
	if _, err := parser.ParseFile(token.NewFileSet(), composegen.FaultsFile, src, parser.AllErrors); err != nil {
		t.Fatalf("does not parse: %v\n%s", err, src)
	}
	body := string(src)
	for _, want := range []string{
		"// Code generated by composegen. DO NOT EDIT.",
		"type faultOrderManager struct",
		"take  func(component, op string) (string, bool)",
		"func applyFaults(profile, url string, managers WebManagers) (WebManagers, error)",
		"managers.OrderManager = faultOrderManager{inner: managers.OrderManager, take: take}",
		`profile != "local"`,
	} {
		if !strings.Contains(body, want) {
			t.Errorf("%s lacks %q:\n%s", composegen.FaultsFile, want, body)
		}
	}
	// every operation of every web-exposed Manager that can fail asks take() first
	c := m.Contracts["orderManager"]
	if c == nil || c.Doc == nil {
		t.Fatal("the fixture has no orderManager contract")
	}
	for _, op := range c.Doc.Interface.Operations {
		if !op.Error {
			continue
		}
		if want := `f.take("orderManager", "` + op.Name + `")`; !strings.Contains(body, want) {
			t.Errorf("%s: operation %s does not ask for a fault (want %q)", composegen.FaultsFile, op.Name, want)
		}
	}
	// the code table is the one the generated handlers answer with, inverted
	for _, want := range []string{`"NotFound"`, `"not_found"`, `fwm.Infrastructure`} {
		if !strings.Contains(body, want) {
			t.Errorf("%s lacks the error-code table entry %s", composegen.FaultsFile, want)
		}
	}
	main := string(got[composegen.MainFile])
	if !strings.Contains(main, "webManagers, err = applyFaults(hooks.ResolveProfile(cfg), scenariohostURL, webManagers)") {
		t.Errorf("the composition root does not install the fault wrapper:\n%s", main)
	}
	if f, n := strings.Index(main, "applyFaults("), strings.Index(main, "applyNullOps("); f < 0 || n < f {
		t.Errorf("the fault wrapper must be inner to the null wrapper (faults at %d, nulls at %d)", f, n)
	}
}
