package modelgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"maps"
	"path/filepath"
	"sort"
	"strings"
)

// nullHeader marks a null.gen.go: it is conformance scaffolding, never an app's own code.
const nullHeader = "// Code generated by nullgen for conformance. DO NOT EDIT.\n" +
	"// Every operation returns the zero value and a nil error, so a model with nothing built\n" +
	"// still compiles and boots. Delete this file when the component is built.\n\n"

// NullFile is the file name GenerateNulls emits into each contract package.
const NullFile = "null.gen.go"

// GenerateNulls emits, per built non-client goPackage, a null.gen.go holding a Null<Iface> for
// every contract in the package: a zero-size type implementing the whole generated interface
// with zero results and nil errors. It also emits the unexported builders contract.gen.go
// delegates to (new<Iface>(deps…), new<Infra><Iface>(params…)) returning the Null, and, for an
// ARTIFACT-mode infra (Git), the methods the app would otherwise write on the generated
// <Infra><Iface> struct. Without them a package holding only generated code does not compile,
// because the generated constructors name hand-written builders that do not exist yet.
//
// The result is keyed by goPackage; a caller writes the bytes to filepath.Join(key, NullFile).
// A stub contract gets its Null type but no builder (its implementation is fully generated).
func GenerateNulls(projectJSON []byte, cfg Config) (map[string][]byte, error) {
	if cfg.ModulePath == "" {
		return nil, fmt.Errorf("modelgen: Config.ModulePath is empty")
	}
	contracts, err := parseServiceContracts(projectJSON)
	if err != nil {
		return nil, err
	}
	resolver, err := buildResolver(contracts)
	if err != nil {
		return nil, err
	}
	keys := make([]string, 0, len(contracts))
	for k := range contracts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	groupOrder, groups, err := selectGroups(keys, contracts, cfg.Only)
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{}
	for _, goPkg := range groupOrder {
		src, wrote, err := emitNullGoPackage(goPkg, groups[goPkg], contracts, cfg.ModulePath, resolver)
		if err != nil {
			return nil, err
		}
		if wrote {
			out[goPkg] = src
		}
	}
	return out, nil
}

// emitNullGoPackage emits one package's null.gen.go; wrote=false means no contract in the group
// carries an interface.
func emitNullGoPackage(goPkg string, keys []string, contracts map[string]json.RawMessage, modulePath string, resolver map[string]contractRef) ([]byte, bool, error) {
	pendingImports = map[string]string{}
	defer func() { pendingImports = map[string]string{} }() // the emission state is one pass's
	var buf bytes.Buffer
	wrote := false
	for _, k := range keys {
		emitted, err := emitNullKey(&buf, contracts[k], modulePath, resolver)
		if err != nil {
			return nil, false, fmt.Errorf("modelgen null %q: %w", k, err)
		}
		wrote = wrote || emitted
	}
	if !wrote {
		return nil, false, nil
	}
	src, err := assembleFormatted(filepath.Base(goPkg), nullHeader, &buf)
	if err != nil {
		return nil, false, fmt.Errorf("modelgen null %q: %w", goPkg, err)
	}
	return src, true, nil
}

// emitNullKey emits one contract entry; false means it carries no interface.
func emitNullKey(buf *bytes.Buffer, raw json.RawMessage, modulePath string, resolver map[string]contractRef) (bool, error) {
	var meta contractMeta
	if err := json.Unmarshal(raw, &meta); err != nil {
		return false, err
	}
	iface, haveIface, err := parseInterfaceOnly(raw)
	if err != nil || !haveIface {
		return false, err
	}
	return true, emitNull(buf, iface, meta, modulePath, resolver)
}

// emitNull writes one contract's Null type, its methods, and the builders the generated
// constructors delegate to.
func emitNull(buf *bytes.Buffer, iface Interface, meta contractMeta, modulePath string, resolver map[string]contractRef) error {
	if _, known := layerContext[iface.Layer]; !known {
		return fmt.Errorf("interface %q: unknown layer %q (want one of %s)", iface.Name, iface.Layer, strings.Join(layerNames(), ", "))
	}
	null := "Null" + iface.Name
	fmt.Fprintf(buf, "// %s implements %s with zero results and nil errors.\n", null, iface.Name)
	fmt.Fprintf(buf, "type %s struct{}\n\n", null)
	fmt.Fprintf(buf, "var _ %s = %s{}\n\n", iface.Name, null)
	emitNullMethods(buf, null, iface)
	if meta.Stub {
		return nil
	}
	if iface.Layer == "manager" {
		// appgen temporal's worker.gen.go registers a Manager only through this method (its
		// workerManifestSource) and panics at boot without it; a null Manager has no workflows.
		fmt.Fprintf(buf, "func (%s) WorkerManifest() genWorkerManifest {\n\treturn genWorkerManifest{}\n}\n\n", null)
	}
	return emitNullBuilders(buf, iface, meta, modulePath, resolver)
}

// emitNullBuilders writes the unexported builder(s) the contract's generated constructor
// delegates to, mirroring emitImplSurface's cases.
func emitNullBuilders(buf *bytes.Buffer, iface Interface, meta contractMeta, modulePath string, resolver map[string]contractRef) error {
	null := "Null" + iface.Name
	switch {
	case iface.Layer == "client":
		return nil
	case usesRAContext(iface.Layer) && len(meta.Infra) > 0:
		return emitNullInfraBuilders(buf, iface, meta.Infra)
	case iface.Layer == "resourceaccess":
		return nil
	default:
		params := make([]string, 0, len(meta.Deps))
		for _, d := range meta.Deps {
			typ, err := depType(d, resolver, modulePath)
			if err != nil {
				return err
			}
			params = append(params, "_ "+typ)
		}
		fmt.Fprintf(buf, "func new%s(%s) %s { return %s{} }\n\n", iface.Name, strings.Join(params, ", "), iface.Name, null)
		return nil
	}
}

// emitNullInfraBuilders writes, per infra, what the generated impl surface leaves to the app: the
// delegated builder for a stateful infra, or the interface methods on the generated struct for
// the ARTIFACT-mode one.
func emitNullInfraBuilders(buf *bytes.Buffer, iface Interface, infra []string) error {
	for _, name := range infra {
		binding, ok := infraBindings[name]
		if !ok {
			return fmt.Errorf("unapproved/unknown infra %q (no framework binding)", name)
		}
		for _, f := range binding.params {
			maps.Copy(pendingImports, f.imports)
		}
		if binding.delegated {
			emitNullDelegatedBuilder(buf, iface, name, binding)
		} else {
			emitNullMethods(buf, "*"+name+iface.Name, iface)
		}
	}
	return nil
}

// emitNullDelegatedBuilder writes the unexported new<Infra><Iface> that emitDelegatingConstructor's
// public constructor calls.
func emitNullDelegatedBuilder(buf *bytes.Buffer, iface Interface, name string, binding infraBinding) {
	null := "Null" + iface.Name
	params := make([]string, 0, len(binding.params))
	for _, f := range binding.params {
		params = append(params, "_ "+f.typ)
	}
	ret, val := iface.Name, null+"{}"
	if binding.returnsError {
		ret, val = "("+iface.Name+", error)", null+"{}, nil"
	}
	fmt.Fprintf(buf, "func new%s%s(%s) %s { return %s }\n\n", name, iface.Name, strings.Join(params, ", "), ret, val)
}

// emitNullMethods writes the interface's methods on recv: every parameter blanked, results zero,
// errors nil.
func emitNullMethods(buf *bytes.Buffer, recv string, iface Interface) {
	lc, hasLayer := layerContext[iface.Layer]
	recvDecl := "(" + recv + ")"
	for _, op := range iface.Operations {
		params := make([]string, 0, len(op.Params)+1)
		if hasLayer {
			params = append(params, "_ "+lc.typ)
			pendingImports[lc.path] = lc.alias
		}
		for _, p := range op.Params {
			params = append(params, "_ "+paramType(p))
		}
		fmt.Fprintf(buf, "func %s %s(%s)%s {\n", recvDecl, op.Name, strings.Join(params, ", "), returnClause(op))
		switch {
		case op.Result != nil && op.Error:
			fmt.Fprintf(buf, "\tvar zero %s\n\treturn zero, nil\n", goType(op.Result))
		case op.Error:
			buf.WriteString("\treturn nil\n")
		case op.Result != nil:
			fmt.Fprintf(buf, "\tvar zero %s\n\treturn zero\n", goType(op.Result))
		}
		buf.WriteString("}\n\n")
	}
}
