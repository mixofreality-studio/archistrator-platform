package modelgen

import (
	"strings"
	"testing"
)

// nullProject has one contract per shape GenerateNulls treats differently: a delegated-infra RA, an
// ARTIFACT-mode (Git) RA, a stub, a Manager with a component dep and a plain dep, and a Client.
const nullProject = `{"serviceContracts":{
"store":{"component":"store","layer":"ResourceAccess","goPackage":"internal/resourceaccess/store","infra":["Postgres"],"$defs":{},
 "interface":{"name":"StoreAccess","layer":"resourceaccess","operations":[
  {"name":"Get","params":[{"name":"id","schema":{"type":"string"}}],"result":{"type":"string"},"error":true},
  {"name":"Touch","params":[],"error":true},
  {"name":"Count","params":[],"result":{"type":"integer"},"error":false},
  {"name":"Reset","params":[],"error":false}]}},
"blobs":{"component":"blobs","layer":"ResourceAccess","goPackage":"internal/resourceaccess/blobs","infra":["Git"],"$defs":{},
 "interface":{"name":"BlobAccess","layer":"resourceaccess","operations":[{"name":"Put","params":[],"error":true}]}},
"parked":{"component":"parked","layer":"ResourceAccess","goPackage":"internal/resourceaccess/parked","stub":true,"$defs":{},
 "interface":{"name":"ParkedAccess","layer":"resourceaccess","operations":[{"name":"Put","params":[],"error":true}]}},
"boss":{"component":"boss","layer":"Manager","goPackage":"internal/manager/boss","$defs":{},
 "deps":[{"name":"store","component":"store"},{"name":"name","goType":"string"}],
 "interface":{"name":"BossManager","layer":"manager","operations":[{"name":"Run","params":[],"error":true}]}},
"ui":{"component":"ui","layer":"Client","goPackage":"internal/client/ui","$defs":{},
 "interface":{"name":"UI","layer":"client","operations":[{"name":"Click","params":[],"error":true}]}}
}}`

func TestGenerateNulls_EveryShape(t *testing.T) {
	got, err := GenerateNulls([]byte(nullProject), Config{ModulePath: "example.com/app"})
	if err != nil {
		t.Fatalf("GenerateNulls: %v", err)
	}
	if _, ok := got["internal/client/ui"]; ok {
		t.Error("a Client contract got a null (its Go is the client generator's)")
	}
	for pkg, wants := range map[string][]string{
		"internal/resourceaccess/store": {
			"type NullStoreAccess struct{}",
			"var _ StoreAccess = NullStoreAccess{}",
			"func (NullStoreAccess) Get(_ fwra.Context, _ string) (string, error) {\n\tvar zero string\n\treturn zero, nil\n}",
			"func (NullStoreAccess) Touch(_ fwra.Context) error {\n\treturn nil\n}",
			"func (NullStoreAccess) Count(_ fwra.Context) int64 {",
			"func (NullStoreAccess) Reset(_ fwra.Context) {\n}",
			"func newPostgresStoreAccess(_ context.Context, _ *pgxpool.Pool) (StoreAccess, error) {\n\treturn NullStoreAccess{}, nil\n}",
		},
		"internal/resourceaccess/blobs": {"func (*GitBlobAccess) Put(_ fwra.Context) error {"},
		"internal/resourceaccess/parked": {
			"type NullParkedAccess struct{}",
		},
		"internal/manager/boss": {
			`"example.com/app/internal/resourceaccess/store"`,
			"func newBossManager(_ store.StoreAccess, _ string) BossManager { return NullBossManager{} }",
			// RegisterManagerWorker panics at boot unless the manager supplies a manifest.
			"func (NullBossManager) WorkerManifest() genWorkerManifest {\n\treturn genWorkerManifest{}\n}",
		},
	} {
		src := string(got[pkg])
		if src == "" {
			t.Errorf("%s: no null emitted", pkg)
			continue
		}
		if !strings.HasPrefix(src, "// Code generated by nullgen") {
			t.Errorf("%s: no generated header", pkg)
		}
		for _, want := range wants {
			if !strings.Contains(src, want) {
				t.Errorf("%s: missing %q in\n%s", pkg, want, src)
			}
		}
	}
	if strings.Contains(string(got["internal/resourceaccess/parked"]), "func new") {
		t.Error("a stub's implementation is fully generated; it needs no builder")
	}
}
