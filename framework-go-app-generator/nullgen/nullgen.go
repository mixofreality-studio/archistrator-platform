// Package nullgen emits the null implementations that let a model with nothing built compile
// and boot: for every non-client contract a null.gen.go in its package (modelgen.GenerateNulls),
// and a cmd/server/hooks.go that answers every seam of the generated composition root with the
// composegen seed plus a null where only the app could answer (composegen.HooksSeedWith).
//
// It exists for the conformance pipeline and for fresh scaffolds. Nothing it writes is an app's
// own code: every file carries the generated-code header, and nullgen refuses to replace a
// hooks.go that does not.
package nullgen

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/mixofreality-studio/archistrator-platform/framework-go-app-generator/composegen"
	"github.com/mixofreality-studio/archistrator-platform/framework-go-app-generator/modelgen"
	"github.com/mixofreality-studio/archistrator-platform/framework-go-projectmodel"
)

const (
	// HooksPath is the module-relative path of the emitted composition-root hooks.
	HooksPath = "cmd/server/hooks.go"

	// Header is the first line of every file nullgen writes.
	Header = "// Code generated by nullgen for conformance. DO NOT EDIT."

	// pdpHook is the seam only the app can answer: the authorization policy.
	pdpHook = "PolicyDecisionPoint"

	defaultContainer = "server"
	defaultEnvPrefix = "APP"
)

// ErrHandwrittenHooks is Write's refusal to replace a hooks.go nullgen did not write.
var ErrHandwrittenHooks = errors.New("nullgen: cmd/server/hooks.go exists and is not nullgen's; refusing to overwrite an app's own composition root")

// Options are what nullgen cannot read from project.json. Container and EnvPrefix take the
// defaults appgen takes (the deployment's first container, "APP"), because a fresh scaffold's
// appgen.json is empty.
type Options struct {
	// ModulePath is the Go module path of the app (the go.mod module line).
	ModulePath string
	// Container is the deployment container to compose; empty selects the default.
	Container string
	// EnvPrefix is the environment-variable namespace; empty selects "APP".
	EnvPrefix string
}

// Output is every file Emit produces: module-relative path to bytes.
type Output struct {
	Files map[string][]byte
}

// Emit renders the null files for projectJSON, which the caller has admitted
// (projectmodel.Load). The null implementations live in each contract's package; hooks.go is
// the composition root's.
func Emit(projectJSON []byte, opts Options) (Output, error) {
	if opts.ModulePath == "" {
		return Output{}, errors.New("nullgen: Options.ModulePath is empty")
	}
	m, err := projectmodel.Load(projectJSON)
	if err != nil {
		return Output{}, err
	}
	nulls, err := modelgen.GenerateNulls(projectJSON, modelgen.Config{ModulePath: opts.ModulePath})
	if err != nil {
		return Output{}, err
	}
	files := map[string][]byte{}
	for goPkg, src := range nulls {
		files[goPkg+"/"+modelgen.NullFile] = src
	}
	hooks, err := emitHooks(m, opts)
	if err != nil {
		return Output{}, err
	}
	files[HooksPath] = hooks
	return Output{Files: files}, nil
}

// emitHooks renders hooks.go over the same composition config appgen builds for a fresh app.
func emitHooks(m *projectmodel.Model, opts Options) ([]byte, error) {
	container := opts.Container
	if container == "" {
		container = defaultContainer
		if m.Deployment != nil && len(m.Deployment.Containers) > 0 {
			container = m.Deployment.Containers[0].Key
		}
	}
	prefix := opts.EnvPrefix
	if prefix == "" {
		prefix = defaultEnvPrefix
	}
	effective := *m
	effective.Deployment = m.EffectiveDeployment(container)
	variantArgs, returnsError := composegen.ExternalHTTPArgs(&effective)
	cfg := composegen.Config{
		ContainerKey: container, ModulePath: opts.ModulePath, PackageName: "main", EnvPrefix: prefix,
		VariantHookArgs: variantArgs, VariantConstructorReturnsError: returnsError,
	}
	seams, err := composegen.HookList(&effective, cfg)
	if err != nil {
		return nil, fmt.Errorf("nullgen: hooks.go: %w", err)
	}
	seed := composegen.SeedOptions{Header: Header + "\n\n", Body: nullBody}
	if slices.ContainsFunc(seams, func(h composegen.Hook) bool { return h.Name == pdpHook }) {
		seed.Extra = permitAllPDP
	}
	src, err := composegen.HooksSeedWith(&effective, cfg, seed)
	if err != nil {
		return nil, fmt.Errorf("nullgen: hooks.go: %w", err)
	}
	return src, nil
}

// nullBody answers the seams the standard seed leaves to the app, or answers with a null.
func nullBody(h composegen.Hook) string {
	switch {
	case h.Name == pdpHook:
		return `if (appHooks{}).ResolveProfile(nil) != "local" {
		panic("nullgen's permit-all policy is for the local profile only")
	}
	return permitAllPDP{}`
	case h.Finalizes != nil:
		// A binding with no arm in the active profile is nil: give the manager the null.
		return "if v == nil {\n\t\treturn " + h.Finalizes.Null + "{}\n\t}\n\treturn v"
	case h.Seed != "":
		return ""
	default:
		return zeroResults(h.Results)
	}
}

// zeroResults is a body returning the zero value of each result type.
func zeroResults(results []string) string {
	if len(results) == 0 {
		return "// nothing to answer"
	}
	var decls, names []string
	for i, typ := range results {
		name := fmt.Sprintf("r%d", i)
		decls = append(decls, "var "+name+" "+typ)
		names = append(names, name)
	}
	return strings.Join(decls, "\n\t") + "\n\treturn " + strings.Join(names, ", ")
}

const permitAllPDP = `// permitAllPDP permits every request. nullgen installs it under the local profile only, so a
// model with nothing built can serve its generated transports.
type permitAllPDP struct{}

func (permitAllPDP) Decide(context.Context, security.Principal, security.Action, security.ResourceRef) (bool, error) {
	return true, nil
}
`

// Write writes out under root. It refuses, writing nothing, when root already holds a hooks.go
// that is not nullgen's own output.
func Write(root string, out Output) error {
	if err := checkHooks(filepath.Join(root, filepath.FromSlash(HooksPath))); err != nil {
		return err
	}
	for path, src := range out.Files {
		dest := filepath.Join(root, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(dest), 0o750); err != nil {
			return err
		}
		if err := os.WriteFile(dest, src, 0o600); err != nil {
			return err
		}
	}
	return nil
}

// checkHooks is nil when path is absent or begins with [Header].
func checkHooks(path string) error {
	existing, err := os.ReadFile(path) // #nosec G304 -- the CLI's own -root
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if !bytes.HasPrefix(existing, []byte(Header)) {
		return ErrHandwrittenHooks
	}
	return nil
}
