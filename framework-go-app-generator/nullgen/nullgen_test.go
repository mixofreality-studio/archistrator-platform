// fixtureCase is one embedded conformance fixture and what its sandbox module needs beyond the
// generated code: the module path its project.json's goImports assume, and the packages those
// imports name that no contract builds.
type fixtureCase struct {
	name, module string
	stubs        map[string]string
}

// The todomvc harvest is the one the pipeline exists for; the greenfield one carries the plain
// deps (func-typed and scalar resolvers) that todomvc lacks, so every kind of hook body is
// exercised.
var cases = []fixtureCase{
	{name: "todomvc", module: "example.com/todomvc"},
	{name: "greenfield", module: "example.com/greenfield/server", stubs: map[string]string{
		"internal/resourceaccess/repolookup/repolookup.go": "package repolookup\n\ntype RepoRef struct{}\n",
		// orderStateAccess binds a result to a bare x-go-type its own package hand-writes.
		"internal/resourceaccess/orderstate/receipt.go": "package orderstate\n\ntype OrderReceipt struct{}\n",
		// ... and its local profile binds a Memory variant, whose constructor the app hand-writes
		// (nullgen builds the generated constructors' builders, not an arbitrary variant's).
		"internal/resourceaccess/orderstate/memory.go": "package orderstate\n\nfunc NewMemoryAccess() Access { return NullAccess{} }\n",
	}},
}

func (fc fixtureCase) raw(t *testing.T) []byte {
	t.Helper()
	raw, err := conformance.Fixture(fc.name)
	if err != nil {
		t.Fatalf("Fixture(%q): %v", fc.name, err)
	}
	return raw
}

func (fc fixtureCase) emit(t *testing.T) (nullgen.Output, *projectmodel.Model) {
	t.Helper()
	raw := fc.raw(t)
	m, err := projectmodel.Load(raw)
	if err != nil {
		t.Fatalf("projectmodel.Load: %v", err)
	}
	out, err := nullgen.Emit(raw, nullgen.Options{ModulePath: fc.module})
	if err != nil {
		t.Fatalf("nullgen.Emit: %v", err)
	}
	return out, m
}

func isGoContract(c *projectmodel.Contract) bool {
	return c.GoPackage != "" && !strings.EqualFold(c.Layer, "client")
}

// Every non-client contract that names a Go package gets a null.gen.go there declaring
// Null<Iface>; a client contract (its Go is the client generator's) gets none.
func TestNullgen_EmitsNullForEveryGoContract(t *testing.T) {
	for _, fc := range cases {
		t.Run(fc.name, func(t *testing.T) {
			out, m := fc.emit(t)
			want := map[string]bool{}
			for key, c := range m.Contracts {
				if !isGoContract(c) {
					continue
				}
				path := c.GoPackage + "/null.gen.go"
				want[path] = true
				src, ok := out.Files[path]
				if !ok {
					t.Errorf("%s: no %s emitted", key, path)
					continue
				}
				decl := "type Null" + c.Doc.Interface.Name + " struct{}"
				if !bytes.Contains(src, []byte(decl)) {
					t.Errorf("%s: %s does not declare %q:\n%s", key, path, decl, src)
				}
				if !bytes.HasPrefix(src, []byte("// Code generated by nullgen")) {
					t.Errorf("%s: %s lacks the generated header", key, path)
				}
			}
			if len(want) == 0 {
				t.Fatal("the fixture has no non-client Go contract; the test proves nothing")
			}
			for path := range out.Files {
				if strings.HasSuffix(path, "/null.gen.go") && !want[path] {
					t.Errorf("unexpected null file %s (a client or package-less contract)", path)
				}
			}
			if _, ok := out.Files[nullgen.HooksPath]; !ok {
				t.Error("no " + nullgen.HooksPath + " emitted")
			}
		})
	}
}

// The null hooks.go answers every seam the generated Hooks interface has: with it in place the
// composition root (the REAL generators' output over the fixture) builds and vets, the generated
// policy test passes, and the null packages compile against their generated contracts.
func TestNullgen_HooksCoverEverySeam(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping the compile sandbox in -short")
	}
	genDir := generatorModuleDir(t)
	bin := buildGenerators(t, genDir)
	for _, fc := range cases {
		t.Run(fc.name, func(t *testing.T) {
			out, m := fc.emit(t)
			dir := t.TempDir()
			scaffoldSandbox(t, dir, genDir, fc, m)
			for path, src := range out.Files {
				writeFile(t, filepath.Join(dir, path), src)
			}
			project := filepath.Join(dir, ".aiarch", "state", "project.json")
			for _, args := range [][]string{
				{"modelgen", "-project", project, "-root", dir},
				{"appgen", "temporal", "-project", project, "-root", dir},
				{"appgen", "config", "-project", project, "-root", dir},
				{"appgen", "compose", "-project", project, "-root", dir},
				{"appgen", "clients", "-project", project, "-root", dir},
			} {
				run(t, dir, filepath.Join(bin, args[0]), args[1:]...)
			}
			hooks, err := os.ReadFile(filepath.Join(dir, "cmd", "server", "hooks.go"))
			if err != nil || !bytes.HasPrefix(hooks, []byte(nullgen.Header)) {
				t.Fatalf("appgen replaced nullgen's hooks.go (err=%v):\n%.200s", err, hooks)
			}
			mainGen, err := os.ReadFile(filepath.Join(dir, "cmd", "server", "main.gen.go"))
			if err != nil {
				t.Fatalf("appgen compose wrote no main.gen.go: %v", err)
			}
			for key, c := range m.Contracts {
				if isGoContract(c) && !bytes.Contains(mainGen, []byte(fc.module+"/"+c.GoPackage)) {
					t.Errorf("%s: the composition root does not wire %s, so its null was not exercised", key, c.GoPackage)
				}
			}
			runGo(t, dir, "build", "./...")
			runGo(t, dir, "vet", "./...")
			runGo(t, dir, "test", "-run", "TestPolicyAdmitsEveryGeneratedRequest", "./cmd/server")
		})
	}
}

// A hooks.go the app wrote is the app's own; nullgen refuses to replace it (the CLI exits 2).
// Its own previous output is replaced.
func TestNullgen_RefusesToOverwriteHandwrittenHooks(t *testing.T) {
	out, _ := cases[0].emit(t)
	root := t.TempDir()
	hooks := filepath.Join(root, filepath.FromSlash(nullgen.HooksPath))
	writeFile(t, hooks, []byte("package main\n\n// handwritten\n"))
	err := nullgen.Write(root, out)
	if !errors.Is(err, nullgen.ErrHandwrittenHooks) {
		t.Fatalf("Write over a handwritten hooks.go: err = %v, want ErrHandwrittenHooks", err)
	}
	if got, _ := os.ReadFile(hooks); !strings.Contains(string(got), "handwritten") {
		t.Error("the handwritten hooks.go was modified")
	}
	if _, statErr := os.Stat(filepath.Join(root, "internal")); statErr == nil {
		t.Error("a refused Write must emit nothing")
	}
	if err := os.Remove(hooks); err != nil {
		t.Fatal(err)
	}
	if err := nullgen.Write(root, out); err != nil {
		t.Fatalf("first Write: %v", err)
	}
	if err := nullgen.Write(root, out); err != nil {
		t.Fatalf("Write over nullgen's own hooks.go must succeed: %v", err)
	}
}

func generatorModuleDir(t *testing.T) string {
	t.Helper()
	dir, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	return dir
}

// scaffoldSandbox writes what a scaffolded app has before any generator runs: a go.mod resolving
// the platform modules from this checkout (GOWORK=off), the project.json, and a doc.go in every
// contracted package so the generators treat each as built.
func scaffoldSandbox(t *testing.T, dir, genDir string, fc fixtureCase, m *projectmodel.Model) {
	t.Helper()
	platform := filepath.Dir(genDir)
	var mod strings.Builder
	mod.WriteString("module " + fc.module + "\n\ngo 1.25.0\n\nrequire (\n")
	replaces := []string{"framework-go", "framework-go-app-generator", "framework-go-http-generator",
		"framework-go-mcp-generator", "framework-go-projectmodel", "framework-go-infrastructure-github",
		"framework-go-infrastructure-keycloak", "framework-go-infrastructure-llm", "framework-go-infrastructure-otel",
		"framework-go-infrastructure-postgres", "framework-go-infrastructure-temporal", "framework-go-scenariohost"}
	const prefix = "github.com/mixofreality-studio/archistrator-platform/"
	for _, r := range replaces {
		mod.WriteString("\t" + prefix + r + " v0.0.0\n")
	}
	mod.WriteString(")\n\n")
	for _, r := range replaces {
		mod.WriteString("replace " + prefix + r + " => " + filepath.Join(platform, r) + "\n")
	}
	writeFile(t, filepath.Join(dir, "go.mod"), []byte(mod.String()))
	if sum, err := os.ReadFile(filepath.Join(genDir, "go.sum")); err == nil {
		writeFile(t, filepath.Join(dir, "go.sum"), sum)
	}
	writeFile(t, filepath.Join(dir, ".aiarch", "state", "project.json"), fc.raw(t))
	for path, src := range fc.stubs {
		writeFile(t, filepath.Join(dir, path), []byte(src))
	}
	for _, c := range m.Contracts {
		if c.GoPackage != "" {
			writeFile(t, filepath.Join(dir, c.GoPackage, "doc.go"), []byte("package "+filepath.Base(c.GoPackage)+"\n"))
		}
	}
}

func writeFile(t *testing.T, path string, src []byte) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		t.Fatal(err)
	}
}

// buildGenerators builds the real CLIs once, so the chain above runs exactly the commands an
// app does.
func buildGenerators(t *testing.T, genDir string) string {
	t.Helper()
	bin := t.TempDir()
	cmd := exec.Command("go", "build", "-o", bin+string(filepath.Separator), "./cmd/modelgen", "./cmd/appgen")
	cmd.Dir = genDir
	cmd.Env = append(os.Environ(), "GOWORK=off")
	if o, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("building the generators: %v\n%s", err, o)
	}
	return bin
}

func run(t *testing.T, dir, name string, args ...string) {
	t.Helper()
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "GOWORK=off", "GOFLAGS=-mod=mod")
	if o, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("%s %v: %v\n%s", filepath.Base(name), args, err, o)
	}
}

func runGo(t *testing.T, dir string, args ...string) {
	t.Helper()
	run(t, dir, "go", args...)
}
