// TestClientDialect pins the classification table.
func TestClientDialect(t *testing.T) {
	action := map[string]any{"name": "action", "schema": map[string]any{"type": "object"}}
	arg := map[string]any{"name": "orderId", "schema": map[string]any{"type": "string"}}
	for _, tc := range []struct {
		name      string
		goPackage string
		ops       []any
		want      dialect
	}{
		{"web actions", "", []any{map[string]any{"name": "Open", "params": []any{action}}}, dialectWeb},
		{"web actions with a package", "internal/client/web", []any{map[string]any{"name": "Open", "params": []any{action}}}, dialectWeb},
		{"tools", "internal/client/mcp", []any{map[string]any{"name": "OrderGetOrder", "params": []any{arg}}}, dialectMCP},
		{"tool with no params", "internal/client/mcp", []any{map[string]any{"name": "OrderList", "params": []any{}}}, dialectMCP},
		{"tool taking action among others", "internal/client/mcp", []any{map[string]any{"name": "Steer", "params": []any{action, arg}}}, dialectMCP},
		{"no ops, a package", "internal/client/mcp", nil, dialectMCP},
		{"routes", "internal/client/web/list", []any{map[string]any{"name": "ListAddTodo", "params": []any{arg}}}, dialectREST},
		{"no ops, no package", "", nil, dialectWeb},
	} {
		raw, err := json.Marshal(map[string]any{"component": "c", "layer": "Client", "goPackage": tc.goPackage, "interface": map[string]any{"name": "C", "layer": "client", "operations": tc.ops}})
		if err != nil {
			t.Fatal(err)
		}
		var sc methodcheck.ServiceContract
		if err := json.Unmarshal(raw, &sc); err != nil {
			t.Fatal(err)
		}
		got, err := clientDialect("c", sc)
		if err != nil {
			t.Errorf("%s: %v", tc.name, err)
			continue
		}
		if got != tc.want {
			t.Errorf("%s: dialect %v, want %v", tc.name, got, tc.want)
		}
	}
}

