func keys(m map[string][]byte) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	slices.Sort(out)
	return out
}

func generate(t *testing.T) Output {
	t.Helper()
	raw, err := os.ReadFile("testdata/project_tp.json")
	if err != nil {
		t.Fatal(err)
	}
	out, err := Generate(raw, Config{ModulePath: "example.com/app/server"})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

func TestGenerate_GoScenarioFileShape(t *testing.T) {
	out := generate(t)
	src, ok := out.Generated[billingGen]
	if !ok {
		t.Fatalf("missing generated file; have %v", keys(out.Generated))
	}
	for _, want := range []string{
		"// Code generated by testgen. DO NOT EDIT.",
		"package billing_test",
		"h := scenariohost.Start(t)\n",
		"func TestScenario_process_order_P2(",
		"func TestScenario_track_order_P1(",
		"h.RunScenario(t, \"billingManager\", \"process-order-P2\"",
		// a step is always a direct call on the generated subject, as the actor's principal
		"out1, err1 = subject.GetInvoice(h.ManagerContextAs(t, principal(\"customer\")), in1.InvoiceId)",
		"\"example.com/app/server/internal/manager/billing\"",
		"\"example.com/app/server/internal/scenariocompose\"",
		"fwm \"github.com/mixofreality-studio/archistrator-platform/framework-go/manager\"",
		"\"github.com/mixofreality-studio/archistrator-platform/framework-go-scenariohost\"",
		"expect(t, \"track-order-P1\", 1, out1, err1, `{\"result\":\"{\\\"id\\\":\\\"inv-o-2\\\",\\\"state\\\":\\\"paid\\\"}\",\"errorExpected\":false}`)",
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("missing %q in\n%s", want, src)
		}
	}
	// TestMain lives in the null file, beside the switch it owns (emit_null.go).
	if strings.Contains(string(src), "func TestMain") {
		t.Errorf("the scenarios file carries no TestMain:\n%s", src)
	}
	null := string(out.Generated[billingNull])
	if !strings.Contains(null, "func TestMain(m *testing.M) {") || !strings.Contains(null, "scenariohost.MainWithWorkflows(m, scenariocompose.Workflows(), \"billingManager\")") {
		t.Errorf("the null file carries the package's TestMain:\n%s", null)
	}
	if strings.Contains(string(src), "probeProcessOrder") {
		t.Errorf("a probe is a closure of direct calls, not a hook:\n%s", src)
	}
	// the same-component probe is a call on the subject itself
	if !strings.Contains(string(src), "return subject.GetInvoice(h.ManagerContextAs(t, principal(\"customer\")), in.InvoiceId)") {
		t.Errorf("same-component probe call missing in\n%s", src)
	}
	if _, err := format.Source(src); err != nil {
		t.Fatalf("not gofmt-able: %v", err)
	}
	for _, want := range []string{
		"type inputProcessOrderP2S1 struct {",
		"InvoiceId string `json:\"invoiceId\"`",
		"Amount    int64  `json:\"amount\"`",
	} {
		if !strings.Contains(string(src), want) {
			t.Errorf("input type missing %q in\n%s", want, src)
		}
	}
}

func TestGenerate_CrossComponentProbeIsADirectCall(t *testing.T) {
	out := generate(t)
	src := string(out.Generated[orderGen])
	if !strings.Contains(src, "return scenariocompose.NewBillingManager(t, h).GetInvoice(h.ManagerContextAs(t, principal(\"customer\")), in.InvoiceId)") {
		t.Errorf("probe on billingManager from orderManager must be a direct call on the generated component:\n%s", src)
	}
	// The probe's parameters are builtin types, so the call goes through scenariocompose alone: importing the
	// component's package as well would be an unused import. (A probe taking one of its types imports it.)
	if strings.Contains(src, "\"example.com/app/server/internal/manager/billing\"") {
		t.Errorf("the probe's component package is not used and must not be imported:\n%s", src)
	}
	// A $ref param is spelled through the contract package.
	if !strings.Contains(src, "Order order.Order `json:\"order\"`") {
		t.Errorf("$ref param type must be package-qualified:\n%s", src)
	}
}

