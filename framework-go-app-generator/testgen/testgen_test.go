func writeAll(t *testing.T, root string, files map[string][]byte) {
	t.Helper()
	for p, b := range files {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestDrift_CleanTreeIsSilent(t *testing.T) {
	out := generate(t)
	root := t.TempDir()
	writeAll(t, root, out.Generated)
	writeAll(t, root, out.HooksOnce)
	msgs, err := Drift(root, out)
	if err != nil {
		t.Fatal(err)
	}
	if len(msgs) != 0 {
		t.Fatalf("clean tree drifted: %v", msgs)
	}
}

