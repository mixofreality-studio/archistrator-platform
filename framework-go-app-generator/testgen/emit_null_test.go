// The run the CLI performs is listed by Generate: one entry per (scenario, stimulus operation), for
// runnable Go bindings only, naming the test, the package and the AIARCH_NULL_OPS value.
func TestNull_ListsDiscriminationRuns(t *testing.T) {
	out := generate(t)
	want := Discrimination{
		Component: "billingManager", Scenario: "process-order-P2", Op: "RecordPayment",
		Package: "internal/manager/billing", Test: "TestScenario_process_order_P2", NullOp: "BillingManager.RecordPayment",
	}
	if !slices.Contains(out.Discriminate, want) {
		t.Errorf("missing %+v in %+v", want, out.Discriminate)
	}
	for _, d := range out.Discriminate {
		if d.Component == "shopClient" {
			t.Errorf("a web client scenario is not a Go run: %+v", d)
		}
	}
	if !slices.IsSortedFunc(out.Discriminate, func(a, b Discrimination) int {
		return strings.Compare(a.Package+a.Test+a.NullOp, b.Package+b.Test+b.NullOp)
	}) {
		t.Errorf("runs are not in a stable order: %+v", out.Discriminate)
	}
}

// nullStubCompose is stubCompose with the Null wrapper composegen emits: the named operations return
// their zero result (and do not run), everything else is the inner subject.
const nullStubCompose = `package scenariocompose

import (
	"strings"
	"testing"

	"example.com/app/server/internal/manager/billing"
	fwm "github.com/mixofreality-studio/archistrator-platform/framework-go/manager"
	"github.com/mixofreality-studio/archistrator-platform/framework-go-scenariohost"
)

type subject struct{ paid bool }

func (s *subject) RecordPayment(fwm.Context, string, int64) error { s.paid = true; return nil }
func (s *subject) GetInvoice(fwm.Context, string) (billing.Invoice, error) {
	if s.paid {
		return billing.Invoice{ID: "inv-o-2", State: "paid"}, nil
	}
	return billing.Invoice{ID: "inv-o-2", State: "requested"}, nil
}

func NewBillingManager(t *testing.T, h *scenariohost.Host) billing.BillingManager { return &subject{} }

type nullBilling struct {
	inner billing.BillingManager
	ops   map[string]bool
}

func NullBillingManager(inner billing.BillingManager, ops ...string) billing.BillingManager {
	m := map[string]bool{}
	for _, o := range ops {
		if op, ok := strings.CutPrefix(o, "BillingManager."); ok {
			m[op] = true
		}
	}
	return nullBilling{inner: inner, ops: m}
}

func (n nullBilling) RecordPayment(ctx fwm.Context, id string, amount int64) error {
	if !n.ops["RecordPayment"] {
		return n.inner.RecordPayment(ctx, id, amount)
	}
	return nil
}

func (n nullBilling) GetInvoice(ctx fwm.Context, id string) (billing.Invoice, error) {
	if !n.ops["GetInvoice"] {
		return n.inner.GetInvoice(ctx, id)
	}
	return billing.Invoice{}, nil
}

func Workflows() scenariohost.Workflows { return scenariohost.Workflows{} }
`

// runWithNull builds a module around the generated billing files and runs one scenario with
// AIARCH_NULL_OPS set to nullOps (empty: unset), returning go test's output.
func runWithNull(t *testing.T, run, nullOps string) (string, error) {
	t.Helper()
	out := generate(t)
	root := writeModule(t, map[string]string{
		"internal/manager/billing/billing.go":                    stubBilling,
		"internal/scenariocompose/compose.go":                    nullStubCompose,
		"internal/manager/billing/manager_scenarios.gen_test.go": string(out.Generated[billingGen]),
		billingNull: string(out.Generated[billingNull]),
	}, moduleOpts{})
	var env []string
	if nullOps != "" {
		env = []string{"AIARCH_NULL_OPS=" + nullOps}
	}
	return goIn(root, env, "test", "-count=1", "-run", run, "./internal/manager/billing/")
}

// The compiled TestMain switch: unset, the scenario passes against the real subject; with the
// stimulus operation nulled the same scenario fails (the stimulus did nothing, so the probe's
// "paid" never came), which is exactly what proves the scenario can fail.
func TestNull_NullingTheStimulusFailsTheScenario(t *testing.T) {
	if testing.Short() {
		t.Skip("compiles a module")
	}
	const run = "^TestScenario_process_order_P2$"
	if out, err := runWithNull(t, run, ""); err != nil {
		t.Fatalf("the real subject must pass:\n%s", out)
	}
	out, err := runWithNull(t, run, "BillingManager.RecordPayment")
	if err == nil {
		t.Fatalf("a scenario whose stimulus is null passed:\n%s", out)
	}
	if !strings.Contains(out, "FAIL") || strings.Contains(out, "build failed") {
		t.Fatalf("expected a test failure, not a build failure:\n%s", out)
	}
}
