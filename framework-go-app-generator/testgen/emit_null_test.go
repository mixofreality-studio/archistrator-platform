const billingNull = "internal/manager/billing/null.gen_test.go"

// Every Go scenario package gets a null.gen_test.go owning the package's TestMain: it reads
// AIARCH_NULL_OPS and, when set, the package's subject is the generated Null wrapper over the real
// one. The scenarios file keeps no TestMain and reaches the switch through one call.
func TestNull_EmitsTestMainSwitch(t *testing.T) {
	out := generate(t)
	null, ok := out.Generated[billingNull]
	if !ok {
		t.Fatalf("no %s; have %v", billingNull, keys(out.Generated))
	}
	src := string(null)
	for _, want := range []string{
		"// Code generated by testgen. DO NOT EDIT.",
		"package billing_test",
		"os.Getenv(\"AIARCH_NULL_OPS\")",
		"func TestMain(m *testing.M) {",
		"scenariohost.MainWithWorkflows(m, scenariocompose.Workflows(), \"billingManager\")",
		"func nullSubjectBillingManager(inner billing.BillingManager) billing.BillingManager {",
		"scenariocompose.NullBillingManager(inner, nullOps...)",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("missing %q in\n%s", want, src)
		}
	}
	if _, err := parser.ParseFile(token.NewFileSet(), billingNull, null, parser.AllErrors); err != nil {
		t.Fatalf("does not parse: %v\n%s", err, src)
	}
	scenarios := string(out.Generated[billingGen])
	if strings.Contains(scenarios, "func TestMain") {
		t.Errorf("the scenarios file must leave TestMain to the null file:\n%s", scenarios)
	}
	if !strings.Contains(scenarios, "subject = nullSubjectBillingManager(subject)") {
		t.Errorf("the scenarios file must route its subject through the null switch:\n%s", scenarios)
	}
}

