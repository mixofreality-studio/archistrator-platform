// layerPkg is the framework package whose call Context a layer's contract
// methods take first, mirroring modelgen's layer table: its alias and import
// path (the generated error match reads the layer's typed Error).
type layerPkg struct {
	alias, path string
}

var layerPkgs = map[string]layerPkg{
	"manager":        {"fwm", "github.com/mixofreality-studio/archistrator-platform/framework-go/manager"},
	"engine":         {"fweng", "github.com/mixofreality-studio/archistrator-platform/framework-go/engine"},
	"resourceaccess": {"fwra", "github.com/mixofreality-studio/archistrator-platform/framework-go/resourceaccess"},
	"utility":        {"fwra", "github.com/mixofreality-studio/archistrator-platform/framework-go/resourceaccess"},
}

// goEmit is one Go package's emission state: the generated file body and the
// imports it needs.
type goEmit struct {
	cfg     Config
	goPkg   string
	pkg     string // package name == import alias (modelgen names the package after goPkg's last segment)
	layer   layerPkg
	multi   bool // several contracts share the package: names carry the interface infix
	manager bool // a manager package: its TestMain hands the host workflows to replay
	body    bytes.Buffer
	imports map[string]bool   // extra import paths (x-go-import bindings, other components' packages)
	subject bool              // ≥1 contract has a runnable binding
	owners  map[string]string // declared Go name → the binding that declares it (claim)
	err     error             // first generation error; emit helpers record it, the file emitters return it

	contracts  map[string]methodcheck.ServiceContract // every contract of the project, by key
	aliases    map[string]string                      // package alias → import path, so two packages cannot share a qualifier
	principals map[string]methodcheck.TestPrincipal   // the union of the package's plans' principals
	usesAs     bool                                   // some step runs as a principal
	usesTime   bool                                   // an arrange call names a duration
	tools      bool                                   // a machine client package: its subject is a served tools surface
}

// newGoEmit starts the emission of goPkg's plans.
func newGoEmit(cfg Config, goPkg string, plans []componentPlan, contracts map[string]methodcheck.ServiceContract) (*goEmit, error) {
	g := &goEmit{
		cfg: cfg, goPkg: goPkg, pkg: path.Base(goPkg), multi: len(plans) > 1,
		imports: map[string]bool{}, owners: map[string]string{},
		contracts: contracts, aliases: map[string]string{}, principals: map[string]methodcheck.TestPrincipal{},
	}
	g.aliases[g.pkg] = cfg.ModulePath + "/" + goPkg
	for _, plan := range plans {
		for name, pr := range plan.Principals {
			if prev, ok := g.principals[name]; ok && !samePrincipal(prev, pr) {
				return nil, fmt.Errorf("testgen: %s: plans disagree on who principal %q is (%s vs %s)", goPkg, name, prev.Subject, pr.Subject)
			}
			g.principals[name] = pr
		}
	}
	return g, nil
}

func samePrincipal(a, b methodcheck.TestPrincipal) bool {
	return a.Subject == b.Subject && slices.Equal(a.Roles, b.Roles) && a.OnBehalfOf == b.OnBehalfOf
}

// fail records the first generation error; later ones are dropped.
func (g *goEmit) fail(err error) {
	if g.err == nil {
		g.err = err
	}
}

// emitGo emits one Go package's generated scenarios file and its null file (the TestMain and the
// null-subject switch, emit_null.go). Nothing else: a Go scenario has no agent-owned code.
func emitGo(out *Output, cfg Config, goPkg, stereotype string, plans []componentPlan, contracts map[string]methodcheck.ServiceContract) error {
	layer, ok := layerPkgs[layerKey(plans[0].Contract)]
	if !ok {
		return fmt.Errorf("testgen: %s: layer %q has no framework call context", goPkg, plans[0].Contract.Layer)
	}
	g, err := newGoEmit(cfg, goPkg, plans, contracts)
	if err != nil {
		return err
	}
	g.layer, g.manager = layer, layerKey(plans[0].Contract) == "manager"
	for _, plan := range plans {
		if err := g.claimPlan(plan); err != nil {
			return err
		}
		g.emitPlan(plan)
	}
	if g.err != nil {
		return g.err
	}
	src, err := g.generatedFile(plans)
	if err != nil {
		return err
	}
	out.Generated[path.Join(goPkg, stereotype+"_scenarios.gen_test.go")] = src
	nullSrc, err := g.nullFile(plans)
	if err != nil {
		return err
	}
	out.Generated[path.Join(goPkg, nullFileName)] = nullSrc
	out.Discriminate = append(out.Discriminate, g.discriminations(plans)...)
	return nil
}

// sharedStereotype is the one file stereotype of every contract in the
// package; contracts of different layers cannot share a package.
func sharedStereotype(goPkg string, plans []componentPlan) (string, error) {
	st := stereotypeOf(plans[0].Contract)
	for _, p := range plans[1:] {
		if s := stereotypeOf(p.Contract); s != st {
			return "", fmt.Errorf("testgen: %s hosts contracts of different layers (%s, %s)", goPkg, st, s)
		}
	}
	return st, nil
}

// plansLabel names the plans' components in an error.
func plansLabel(plans []componentPlan) string {
	keys := make([]string, 0, len(plans))
	for _, p := range plans {
		keys = append(keys, p.Key)
	}
	return strings.Join(keys, ", ")
}

// ---- naming ----

// tag is the infix every per-binding name carries in a package several
// contracts share (two contracts there can bind the SAME scenario id).
func (g *goEmit) tag(plan componentPlan) string {
	if !g.multi {
		return ""
	}
	return ifaceName(plan)
}

// ifaceName is the contract's Go interface name, falling back to the
// exported contract key for a contract that names none.
func ifaceName(plan componentPlan) string {
	return contractIface(plan.Key, plan.Contract)
}

func contractIface(key string, sc methodcheck.ServiceContract) string {
	if n := sc.Interface.Name; n != "" {
		return n
	}
	return exportName(key)
}

func exportName(s string) string {
	if s == "" {
		return s
	}
	return strings.ToUpper(s[:1]) + s[1:]
}

func (g *goEmit) subjectType(plan componentPlan) string { return g.pkg + "." + ifaceName(plan) }

// testName keeps the spec's TestScenario_<id> spelling: revive exempts Test*
// funcs in test files, and `make test-scenarios` and the construct workflow
// select the tests with -run 'TestScenario_'.
func (g *goEmit) testName(plan componentPlan, id string) string {
	tag := ""
	if g.multi {
		tag = "_" + ident(ifaceName(plan))
	}
	return "TestScenario" + tag + "_" + ident(id)
}
func (g *goEmit) inputName(plan componentPlan, id string, seq int) string {
	return hookName(inputPrefix, g.tag(plan), id, seq)
}

// claimPlan claims every name one contract's bindings declare in the package:
// each scenario test and each step's input type.
func (g *goEmit) claimPlan(plan componentPlan) error {
	for _, bs := range plan.Scenarios {
		id := bs.Scenario.ID
		owner := plan.Key + " " + id
		if err := g.claim(g.testName(plan, id), owner); err != nil {
			return err
		}
		for _, st := range bs.Steps {
			if err := g.claim(g.inputName(plan, id, st.Bind.Seq), fmt.Sprintf("%s step %d", owner, st.Bind.Seq)); err != nil {
				return err
			}
		}
	}
	return nil
}

// ---- components other than the subject ----

// target is a component a generated test calls: the subject itself, a probe's
// component, an arrange call's component. It is built by scenariocompose.
type target struct {
	key, iface, alias, layer string
	sc                       methodcheck.ServiceContract
}

// construct is the expression building the target through the generated compose package.
func (t target) construct() string {
	return scenarioComposeName + ".New" + t.iface + "(t, h)"
}

// targetFor resolves a probe's or an arrange call's component to its contract, importing its package.
func (g *goEmit) targetFor(component string) (target, error) {
	key, sc, ok := g.findContract(component)
	if !ok {
		return target{}, fmt.Errorf("testgen: %s: component %q has no service contract to call", g.goPkg, component)
	}
	if isClient(sc) {
		return target{}, fmt.Errorf("testgen: %s: component %q is a client: a generated Go test cannot call it", g.goPkg, component)
	}
	if sc.GoPackage == "" {
		return target{}, fmt.Errorf("testgen: %s: component %q has no goPackage, so the generated test cannot import it", g.goPkg, component)
	}
	t := target{key: key, iface: contractIface(key, sc), alias: path.Base(sc.GoPackage), layer: layerKey(sc), sc: sc}
	imp := g.cfg.ModulePath + "/" + sc.GoPackage
	if prev, ok := g.aliases[t.alias]; ok && prev != imp {
		return target{}, fmt.Errorf("testgen: %s: packages %s and %s are both named %q, so the generated test cannot import both", g.goPkg, prev, imp, t.alias)
	}
	g.aliases[t.alias] = imp
	g.imports[g.cfg.ModulePath+"/"+scenarioComposeDir] = true
	return t, nil
}

// findContract resolves a component name to its contract: the key exactly, then
// under scenario.Normalize (the derivation's own fold).
func (g *goEmit) findContract(component string) (string, methodcheck.ServiceContract, bool) {
	return findContractIn(g.contracts, component)
}

// findContractIn resolves a component name among contracts: the key exactly, then under
// scenario.Normalize.
func findContractIn(contracts map[string]methodcheck.ServiceContract, component string) (string, methodcheck.ServiceContract, bool) {
	if sc, ok := contracts[component]; ok {
		return component, sc, true
	}
	want := scenario.Normalize(component)
	for _, key := range sortedKeys(contracts) {
		if scenario.Normalize(key) == want {
			return key, contracts[key], true
		}
	}
	return "", methodcheck.ServiceContract{}, false
}

// ownTarget is the plan's own contract as a target (its package is already imported).
func (g *goEmit) ownTarget(plan componentPlan) target {
	return target{key: plan.Key, iface: ifaceName(plan), alias: g.pkg, layer: layerKey(plan.Contract), sc: plan.Contract}
}

// sameComponent reports a probe or arrange component that names the plan's own.
func sameComponent(plan componentPlan, component string) bool {
	return scenario.Normalize(component) == scenario.Normalize(plan.Key)
}

// stepPrincipal is the plan's principal for the actor that originates the step: the stimulus's
// caller, or one of the callers an alt group folded into it. "" when the caller is a component
// or the plan records no identity for it.
func stepPrincipal(plan componentPlan, st boundStep) string {
	for _, from := range append([]string{st.Stim.Input.From}, st.Stim.Input.Via...) {
		if _, ok := plan.Principals[from]; ok {
			return from
		}
	}
	return ""
}

// hostRecv and probeRecv are the receivers of the generated call-context methods: the scenario host,
// and the bounded probe context a probe closure opens (probeOpen).
const (
	hostRecv  = "h"
	probeRecv = "pc"
)

// probeOpen is the first statement of every probe closure: the context all of that probe's calls are
// made with, bounded by the host's probe deadline so a read that never returns cannot hang the test.
const probeOpen = probeRecv + " := h.ProbeContext(t)"

// ctxExpr is the layer call context a call into a component of the given layer is made with:
// the principal's when the step runs as one, the host's anonymous one otherwise. key makes a
// ResourceAccess call's idempotency key distinct per call site. recv is hostRecv, or probeRecv inside
// a probe closure.
func (g *goEmit) ctxExpr(recv, layer, principalName, key string) string {
	as := ""
	if principalName != "" {
		g.usesAs = true
		as = "principal(" + strconv.Quote(principalName) + ")"
	}
	switch layer {
	case "manager":
		return ctxCall(recv, "ManagerContext", as, "")
	case "engine":
		return ctxCall(recv, "EngineContext", as, "")
	case "resourceaccess", "utility":
		return ctxCall(recv, "ResourceAccessContext", as, strconv.Quote(key))
	}
	g.fail(fmt.Errorf("testgen: %s: layer %q has no framework call context", g.goPkg, layer))
	return "nil"
}

func ctxCall(recv, name, as, key string) string {
	args := []string{"t"}
	if as != "" {
		name += "As"
		args = append(args, as)
	}
	if key != "" {
		args = append(args, key)
	}
	return recv + "." + name + "(" + strings.Join(args, ", ") + ")"
}

// ---- generated file ----

func (g *goEmit) emitPlan(plan componentPlan) {
	for _, bs := range plan.Scenarios {
		if bs.Binding.Skip == nil {
			g.subject = true
			for _, st := range bs.Steps {
				g.emitInputType(plan, bs, st)
			}
		}
		g.emitScenario(plan, bs)
	}
}

// emitInputType declares the named struct a step's inputs decode into: one
// exported field per contract parameter, typed as modelgen types it.
func (g *goEmit) emitInputType(plan componentPlan, bs boundScenario, st boundStep) {
	name := g.inputName(plan, bs.Scenario.ID, st.Bind.Seq)
	fmt.Fprintf(&g.body, "// %s is step %d's parameters of %s, decoded from the binding's inputs.\n", name, st.Bind.Seq, st.Op.Name)
	fmt.Fprintf(&g.body, "type %s %s\n\n", name, g.paramsStruct(g.pkg, st.Op))
}

// paramsStruct spells an operation's parameter list as a struct type literal, its types
// qualified as seen from outside the package aliased alias.
func (g *goEmit) paramsStruct(alias string, op methodcheck.ContractOperation) string {
	if len(op.Params) == 0 {
		return "struct{}"
	}
	var b strings.Builder
	b.WriteString("struct {\n")
	for _, p := range op.Params {
		fmt.Fprintf(&b, "\t%s %s `json:%q`\n", exportName(p.Name), g.paramType(alias, p), p.Name)
	}
	b.WriteString("}")
	return b.String()
}

// paramType is the Go type of one parameter as spelled from outside the
// contract package, recording any x-go-import the type needs.
func (g *goEmit) paramType(alias string, p methodcheck.ContractParam) string {
	typ, imports := modelgen.GoTypeFor(decodeSchema(p.Schema), alias)
	for _, imp := range imports {
		g.imports[imp] = true
	}
	if p.Pointer {
		typ = "*" + typ
	}
	return typ
}

func decodeSchema(raw json.RawMessage) *jsonschema.Schema {
	if len(raw) == 0 || string(raw) == "null" {
		return nil
	}
	var s jsonschema.Schema
	if err := json.Unmarshal(raw, &s); err != nil {
		return nil
	}
	return &s
}

func (g *goEmit) emitScenario(plan componentPlan, bs boundScenario) {
	name := g.testName(plan, bs.Scenario.ID)
	fmt.Fprintf(&g.body, "// %s — %s (use case %s; path %s).\n", name, bs.Scenario.Title, bs.Scenario.UseCase, strings.Join(bs.Scenario.Path, " → "))
	fmt.Fprintf(&g.body, "func %s(t *testing.T) {\n", name)
	g.body.WriteString("\th := scenariohost.Start(t)\n")
	// The verdict is keyed by (component, scenario): facets sharing this
	// package can bind the same scenario id, each into its own results.json.
	fmt.Fprintf(&g.body, "\th.RunScenario(t, %q, %q, func(t *testing.T) {\n", plan.Key, bs.Scenario.ID)
	switch {
	case bs.Binding.Skip != nil:
		fmt.Fprintf(&g.body, "\t\tt.Skip(%q)\n", bs.Binding.Skip.Reason+" (until "+bs.Binding.Skip.Until+")")
	default:
		g.imports[g.cfg.ModulePath+"/"+scenarioComposeDir] = true
		fmt.Fprintf(&g.body, "\t\tvar subject %s = %s\n", g.subjectType(plan), g.ownTarget(plan).construct())
		fmt.Fprintf(&g.body, "\t\tsubject = %s(subject) // the null-subject run (AIARCH_NULL_OPS) swaps the subject here\n", nullSubjectFunc(plan))
		if len(bs.Steps) == 0 {
			g.body.WriteString("\t\t_ = subject // the binding carries no steps\n")
		}
		g.emitArrange(plan, bs)
		d := goDialect{g: g}
		for _, st := range bs.Steps {
			g.emitStep(d, plan, bs, st)
		}
	}
	g.body.WriteString("\t})\n}\n\n")
}

// goDialect drives the subject by calling its Go interface directly.
type goDialect struct{ g *goEmit }

func (goDialect) stepComment(st boundStep, bs boundScenario) string {
	return fmt.Sprintf("step %d: %s (node %s%s)", st.Bind.Seq, st.Op.Name, st.Stim.Node, guardNote(bs.Scenario))
}

// stepCall decodes the step's inputs into its named input type, threads its refs and calls the subject as
// the step's principal.
func (d goDialect) stepCall(plan componentPlan, bs boundScenario, st boundStep, out, errVar string) []string {
	g := d.g
	seq := st.Bind.Seq
	call := directCall{
		recv: "subject", alias: g.pkg, sc: plan.Contract, op: st.Op, inputs: st.Bind.Inputs,
		ctx:   g.ctxExpr(hostRecv, layerKey(plan.Contract), stepPrincipal(plan, st), strconv.Itoa(seq)),
		inVar: fmt.Sprintf("in%d", seq), inType: g.inputName(plan, bs.Scenario.ID, seq),
		scenario: bs.Scenario.ID, seq: seq,
	}
	return g.directLines(call, func(c string) string { return assignStmt(st.Op, c, out, errVar) })
}

// probeBody is the body of the closure running one probe: a direct call on the subject when the probe
// reads its own contract, on the probe's component otherwise, as the step's principal.
func (d goDialect) probeBody(plan componentPlan, bs boundScenario, st boundStep, n int, pr methodcheck.Probe) []string {
	g := d.g
	tgt, recv, err := g.probeTarget(plan, pr)
	if err != nil {
		g.fail(err)
		return nil
	}
	op, ok := operationNamed(tgt.sc, pr.Operation)
	if !ok {
		g.fail(fmt.Errorf("testgen: %s scenario %q step %d probe %d: operation %q is not on %s", plan.Key, bs.Scenario.ID, st.Bind.Seq, n, pr.Operation, tgt.key))
		return nil
	}
	call := directCall{
		recv: recv, alias: tgt.alias, sc: tgt.sc, op: op, inputs: pr.Inputs,
		ctx:   g.ctxExpr(probeRecv, tgt.layer, stepPrincipal(plan, st), fmt.Sprintf("%d.%d", st.Bind.Seq, n)),
		inVar: "in", scenario: bs.Scenario.ID, seq: st.Bind.Seq,
	}
	return append([]string{probeOpen}, g.directLines(call, func(c string) string { return returnStmt(op, c) })...)
}

// probeTarget is the component a probe reads and the expression calling it: the subject when it is the
// plan's own contract, the generated compose package's constructor otherwise.
func (g *goEmit) probeTarget(plan componentPlan, pr methodcheck.Probe) (target, string, error) {
	if sameComponent(plan, pr.Component) {
		return g.ownTarget(plan), "subject", nil
	}
	tgt, err := g.targetFor(pr.Component)
	return tgt, tgt.construct(), err
}

// directCall is one call of a component's Go interface from a generated test.
type directCall struct {
	recv     string // the expression the operation is called on
	alias    string // the qualifier of the operation's parameter types
	sc       methodcheck.ServiceContract
	op       methodcheck.ContractOperation
	inputs   []methodcheck.TestArg
	ctx      string // the call context expression
	inVar    string // the variable the inputs decode into
	inType   string // its type; empty declares an anonymous struct of the operation's parameters
	scenario string // for ref failures
	seq      int
}

// directLines are the statements declaring a call's inputs, decoding the literal ones, threading the refs from
// earlier results, and finishing with finish(call expression). Ref arguments are threaded; an arrange call has
// no earlier result to read, so its refs are refused where it is emitted.
func (g *goEmit) directLines(c directCall, finish func(call string) string) []string {
	args, refs, err := inputsJSON(c.sc, c.op, c.inputs)
	if err != nil {
		g.fail(err)
		return nil
	}
	typ := c.inType
	if typ == "" {
		typ = g.paramsStruct(c.alias, c.op)
		g.importIfQualified(c.alias, typ)
	}
	lines := []string{
		fmt.Sprintf("var %s %s", c.inVar, typ),
		fmt.Sprintf("mustUnmarshal(t, %s, &%s)", rawString(args), c.inVar),
	}
	for _, r := range refs {
		lines = append(lines, fmt.Sprintf("refInto(t, %q, %d, %s, %q, &%s.%s)", c.scenario, c.seq, refSource(r.ref), r.ref.Path, c.inVar, exportName(r.param)))
	}
	return append(lines, finish(callExpr(c.recv, c.op, c.ctx, c.inVar)))
}

// importIfQualified imports the package aliased alias when the type text names one of its types. A call into
// a component whose parameters are all builtin types needs no import of its package: the call goes through
// scenariocompose.
func (g *goEmit) importIfQualified(alias, typ string) {
	if alias == g.pkg && !g.tools { // a component file already imports its own package (generatedImports); a machine client's own name was released in emitMCP, so a same-named component package it probes must be imported
		return
	}
	if regexp.MustCompile(`[\s*\[\]]` + regexp.QuoteMeta(alias) + `\.[A-Z]`).MatchString(typ) {
		g.imports[g.aliases[alias]] = true
	}
}

// refSource is the variable a ref reads: a step's result, or a probe's.
func refSource(r methodcheck.RefValue) string {
	if r.Probe != nil {
		return fmt.Sprintf("pout%d_%d", r.Step, *r.Probe+1)
	}
	return fmt.Sprintf("out%d", r.Step)
}

// callExpr spells a direct call of op on recv with the decoded inputs in inVar.
func callExpr(recv string, op methodcheck.ContractOperation, ctx, inVar string) string {
	args := []string{ctx}
	for _, p := range op.Params {
		args = append(args, inVar+"."+exportName(p.Name))
	}
	return fmt.Sprintf("%s.%s(%s)", recv, op.Name, strings.Join(args, ", "))
}

func hasResult(op methodcheck.ContractOperation) bool {
	return len(op.Result) > 0 && string(op.Result) != "null"
}

// assignStmt assigns whatever call returns to outVar / errVar.
func assignStmt(op methodcheck.ContractOperation, call, outVar, errVar string) string {
	switch {
	case hasResult(op) && op.Error:
		return outVar + ", " + errVar + " = " + call
	case hasResult(op):
		return outVar + " = " + call
	case op.Error:
		return errVar + " = " + call
	default:
		return call
	}
}

// returnStmt returns call's outcome as the (any, error) of a probe closure.
func returnStmt(op methodcheck.ContractOperation, call string) string {
	switch {
	case hasResult(op) && op.Error:
		return "return " + call
	case hasResult(op):
		return "return " + call + ", nil"
	case op.Error:
		return "return nil, " + call
	default:
		return call + "\n\t\t\treturn nil, nil"
	}
}

func guardNote(s scenario.Scenario) string {
	var gs []string
	for _, g := range s.Guards {
		gs = append(gs, g.At+"="+g.Guard)
	}
	if len(gs) == 0 {
		return ""
	}
	return "; guards " + strings.Join(gs, ", ")
}

// refArg is a ref-valued argument: the parameter it fills and the earlier result it reads.
type refArg struct {
	param string
	ref   methodcheck.RefValue
}

// inputsJSON builds the JSON object a call's literal inputs decode from: one
// key per contract parameter, in contract order, carrying the binding's value —
// raw when it parses as JSON and the parameter is not string-typed, quoted
// otherwise. A parameter the binding leaves unnamed is omitted (zero value); a
// ref-valued one is omitted too and returned in refs, to be threaded in at run
// time from the result it names.
func inputsJSON(sc methodcheck.ServiceContract, op methodcheck.ContractOperation, inputs []methodcheck.TestArg) (string, []refArg, error) {
	var parts []string
	var refs []refArg
	for _, p := range op.Params {
		arg, ok := argNamed(inputs, p.Name)
		if !ok {
			continue
		}
		switch v := arg.Value.(type) {
		case methodcheck.LiteralValue:
			parts = append(parts, strconv.Quote(p.Name)+":"+jsonValue(string(v.JSON), isStringSchema(sc, p.Schema)))
		case methodcheck.RefValue:
			refs = append(refs, refArg{param: p.Name, ref: v})
		case methodcheck.PlanRef:
			return "", nil, planRefError(arg)
		}
	}
	return "{" + strings.Join(parts, ",") + "}", refs, nil
}

func argNamed(inputs []methodcheck.TestArg, name string) (methodcheck.TestArg, bool) {
	for _, a := range inputs {
		if a.Name == name {
			return a, true
		}
	}
	return methodcheck.TestArg{}, false
}

// readsStep reports whether an input list reads a result of step seq.
func readsStep(inputs []methodcheck.TestArg, seq int) bool {
	return slices.ContainsFunc(inputs, func(a methodcheck.TestArg) bool {
		v, ok := a.Value.(methodcheck.RefValue)
		return ok && v.Step == seq
	})
}

// jsonValue is one binding value as the JSON the generated step unmarshals. A
// value that is valid JSON is embedded as-is — for a string-typed parameter only
// when it is already a JSON string literal ("\"abc\""), which is how methodcheck's
// TP-ARG-TYPE reads it (the single source of truth for a binding value's type);
// any other value of a string-typed parameter is the string's raw text and is
// quoted.
func jsonValue(value string, stringTyped bool) string {
	if json.Valid([]byte(value)) && (!stringTyped || isJSONStringLiteral(value)) {
		return value
	}
	quoted, _ := json.Marshal(value)
	return string(quoted)
}

// isJSONStringLiteral reports whether a valid JSON text is a string literal.
func isJSONStringLiteral(value string) bool {
	return strings.HasPrefix(strings.TrimSpace(value), `"`)
}

// isStringSchema reports whether a parameter schema is string-typed, following
// one $ref into the contract's $defs.
func isStringSchema(sc methodcheck.ServiceContract, raw json.RawMessage) bool {
	s := decodeSchema(raw)
	if s == nil {
		return false
	}
	if s.Ref != "" {
		def, ok := sc.Defs[strings.TrimPrefix(s.Ref, "#/$defs/")]
		if !ok {
			return false
		}
		s = decodeSchema(def)
		if s == nil {
			return false
		}
	}
	return s.Type == "string" || slices.Contains(s.Types, "string")
}

// expectJSON is the binding expectation as the generated expect helper reads it.
func expectJSON(e methodcheck.TestExpect) string {
	raw, _ := json.Marshal(e)
	return string(raw)
}

// rawString spells s as a Go string literal: a raw literal when it carries no
// backtick, an interpreted one otherwise.
func rawString(s string) string {
	if strings.Contains(s, "`") {
		return strconv.Quote(s)
	}
	return "`" + s + "`"
}

// generatedFile assembles header, package clause, imports, the scenario tests
// and the helpers, gofmt'd. The package's TestMain is not here: it lives in the
// null file (emit_null.go), beside the switch it owns.
func (g *goEmit) generatedFile(plans []componentPlan) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(genHeader + "\n")
	for _, plan := range plans {
		fmt.Fprintf(&b, "// Source: project.json .phaseArtifacts.testPlan.%s × scenario.ForComponent(%q)\n", plan.Key, plan.Key)
	}
	fmt.Fprintf(&b, "\npackage %s_test\n\n", g.pkg)
	g.writeImports(&b, g.generatedImports())
	b.Write(g.body.Bytes())
	if g.subject {
		g.writeHelpers(&b)
	}
	src, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("testgen: %s: generated file does not format: %w\n%s", g.goPkg, err, b.String())
	}
	return src, nil
}

// replays reports whether the package's scenarios are replay-gated: a
// manager package with a runnable binding (with none, no scenario runs a workflow).
func (g *goEmit) replays() bool { return g.manager && g.subject }

// generatedImports is the import set of the generated file: the test
// essentials always; the helpers', the layer's, the contract package's and the
// compose package's when any binding runs.
func (g *goEmit) generatedImports() map[string]string {
	imps := map[string]string{}
	if g.body.Len() == 0 {
		return imps // no scenario at all: the file is its package clause
	}
	imps["testing"], imps[scenarioHostImport] = "", ""
	if !g.subject {
		return imps
	}
	for _, p := range []string{"context", "encoding/json", "errors", "fmt", "reflect", "strings"} {
		imps[p] = ""
	}
	imps[g.layer.path] = g.layer.alias
	imps[g.cfg.ModulePath+"/"+g.goPkg] = ""
	imps[g.cfg.ModulePath+"/"+scenarioComposeDir] = ""
	if g.usesTime {
		imps["time"] = ""
	}
	for p := range g.imports {
		imps[p] = ""
	}
	return imps
}

// writeImports writes one import block, standard library first; gofmt sorts
// within each group.
func (g *goEmit) writeImports(b *bytes.Buffer, imps map[string]string) {
	if len(imps) == 0 {
		return
	}
	var std, rest []string
	for p := range imps {
		if strings.Contains(strings.SplitN(p, "/", 2)[0], ".") {
			rest = append(rest, p)
		} else {
			std = append(std, p)
		}
	}
	sort.Strings(std)
	sort.Strings(rest)
	b.WriteString("import (\n")
	for _, p := range std {
		writeImport(b, p, imps[p])
	}
	if len(rest) > 0 {
		b.WriteString("\n")
	}
	for _, p := range rest {
		writeImport(b, p, imps[p])
	}
	b.WriteString(")\n\n")
}

func writeImport(b *bytes.Buffer, p, alias string) {
	if alias != "" {
		fmt.Fprintf(b, "\t%s %q\n", alias, p)
		return
	}
	fmt.Fprintf(b, "\t%q\n", p)
}

// writeHelpers emits the per-file helpers. They are duplicated per generated
// file on purpose: the file is black-box and self-contained, and the scenario
// host stays a boot-and-record concern.
func (g *goEmit) writeHelpers(b *bytes.Buffer) {
	if g.usesAs {
		writePrincipalTable(b, g.principals)
	}
	fmt.Fprintf(b, expectHelpers, "`")
	b.WriteString(refHelpers)
	fmt.Fprintf(b, layerErrorHasCode, g.layer.alias)
	b.WriteString(matchHelpers)
}

// writePrincipalTable emits the principals map and its lookup.
func writePrincipalTable(b *bytes.Buffer, principals map[string]methodcheck.TestPrincipal) {
	b.WriteString("// principals are the identities the test plan runs its actors as\n// (project.json .phaseArtifacts.testPlan.<component>.principals).\n")
	b.WriteString("var principals = map[string]scenariohost.Principal{\n")
	for _, name := range sortedKeys(principals) {
		pr := principals[name]
		roles := ""
		if len(pr.Roles) > 0 {
			roles = ", Roles: " + quotedStringList(pr.Roles)
		}
		onBehalfOf := ""
		if pr.OnBehalfOf != "" {
			onBehalfOf = ", OnBehalfOf: " + strconv.Quote(pr.OnBehalfOf)
		}
		if len(pr.Intents) > 0 {
			onBehalfOf += ", Intents: " + quotedStringList(pr.Intents)
		}
		fmt.Fprintf(b, "\t%s: {Subject: %s%s%s},\n", strconv.Quote(name), strconv.Quote(pr.Subject), roles, onBehalfOf)
	}
	b.WriteString("}\n\n")
	b.WriteString(principalLookup)
}

// quotedStringList spells items as a Go []string literal.
func quotedStringList(items []string) string {
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = strconv.Quote(s)
	}
	return "[]string{" + strings.Join(quoted, ", ") + "}"
}

// principalLookup is the lookup of a plan principal by actor name.
const principalLookup = `// principal is the identity the plan records for an actor.
func principal(name string) scenariohost.Principal {
	p, ok := principals[name]
	if !ok {
		panic("testgen: the test plan has no principal " + name)
	}
	return p
}

`

// expectHelpers is the decode-and-assert block every generated Go file
// carries, whatever its subject: %[1]s is a backtick (the struct tags; a raw
// literal cannot hold one). It calls errorHasCode, which each dialect spells.
const expectHelpers = `func mustUnmarshal(t *testing.T, raw string, into any) {
	t.Helper()
	if err := json.Unmarshal([]byte(raw), into); err != nil {
		t.Fatalf("testgen: decode %%s: %%v", raw, err)
	}
}

// check judges one outcome against its expectation: an expected error must
// arrive (carrying the expected code, when one is named); an unexpected error
// fails; a named result must be a JSON subset of the marshalled outcome. It
// returns "" when the expectation holds, the failure otherwise.
func check(scenario string, seq int, out any, err error, expectJSON string) string {
	var want struct {
		Result        string %[1]sjson:"result"%[1]s
		ErrorExpected bool   %[1]sjson:"errorExpected"%[1]s
		ErrorCode     string %[1]sjson:"errorCode"%[1]s
	}
	if e := json.Unmarshal([]byte(expectJSON), &want); e != nil {
		return fmt.Sprintf("testgen: decode %%s: %%v", expectJSON, e)
	}
	if want.ErrorExpected {
		if err == nil {
			return fmt.Sprintf("%%s step %%d: expected error %%q, got nil", scenario, seq, want.ErrorCode)
		}
		if want.ErrorCode != "" && !errorHasCode(err, want.ErrorCode) {
			return fmt.Sprintf("%%s step %%d: expected error code %%q, got %%v", scenario, seq, want.ErrorCode, err)
		}
		return ""
	}
	if err != nil {
		return fmt.Sprintf("%%s step %%d: unexpected error: %%v", scenario, seq, err)
	}
	if want.Result != "" && !resultMatches(want.Result, out) {
		got, _ := json.Marshal(out)
		return fmt.Sprintf("%%s step %%d: result %%s is not a subset of %%s", scenario, seq, want.Result, got)
	}
	return ""
}

// expect fails the test unless the outcome meets its expectation.
func expect(t *testing.T, scenario string, seq int, out any, err error, expectJSON string) {
	t.Helper()
	if msg := check(scenario, seq, out, err, expectJSON); msg != "" {
		t.Fatal(msg)
	}
}

// probeTimedOut reports a probe read that ran past its deadline: a read that does not return is
// neither a result nor an expected error, so no expectation is judged against it.
func probeTimedOut(err error) bool {
	return err != nil && (errors.Is(err, context.DeadlineExceeded) || strings.Contains(err.Error(), "deadline exceeded"))
}

// expectProbe is expect for a probe's read: a read that timed out fails the step with that, instead
// of being judged against the expectation (an expected error would otherwise accept the timeout).
func expectProbe(t *testing.T, scenario string, seq int, out any, err error, expectJSON string) {
	t.Helper()
	if probeTimedOut(err) {
		t.Fatalf("%%s step %%d: probe timed out: %%v", scenario, seq, err)
	}
	expect(t, scenario, seq, out, err, expectJSON)
}

// held reports whether the outcome of run already meets expectJSON: the pre-state
// reading of the differential. A read that timed out held nothing: it does not count as the
// expectation already being true.
func held(scenario string, seq int, run func() (any, error), expectJSON string) bool {
	out, err := run()
	if probeTimedOut(err) {
		return false
	}
	return check(scenario, seq, out, err, expectJSON) == ""
}

// differential fails a step whose every probe expectation held before the step
// ran: a test whose assertions were already true proves nothing about the step.
func differential(t *testing.T, scenario string, seq int, pre ...bool) {
	t.Helper()
	for _, was := range pre {
		if !was {
			return
		}
	}
	if len(pre) > 0 {
		t.Fatalf("%%s step %%d: vacuous: every probe expectation already held before the step ran, so the step proves nothing", scenario, seq)
	}
}

`

// refHelpers thread an earlier result into a later argument.
const refHelpers = `// pathValue reads path from the JSON form of from: dot-separated member
// names, each optionally followed by [] (the first element of an array); ""
// is the value itself.
func pathValue(from any, path string) (any, error) {
	raw, err := json.Marshal(from)
	if err != nil {
		return nil, err
	}
	var v any
	if err := json.Unmarshal(raw, &v); err != nil {
		return nil, err
	}
	if path == "" {
		return v, nil
	}
	for _, seg := range strings.Split(path, ".") {
		name, arrays := seg, 0
		for strings.HasSuffix(name, "[]") {
			name = strings.TrimSuffix(name, "[]")
			arrays++
		}
		if name != "" {
			obj, ok := v.(map[string]any)
			if !ok {
				return nil, fmt.Errorf("path %q: no object to read member %q from", path, name)
			}
			if v, ok = obj[name]; !ok {
				return nil, fmt.Errorf("path %q: no member %q", path, name)
			}
		}
		for ; arrays > 0; arrays-- {
			arr, ok := v.([]any)
			if !ok || len(arr) == 0 {
				return nil, fmt.Errorf("path %q: %q is not a non-empty array", path, seg)
			}
			v = arr[0]
		}
	}
	return v, nil
}

// refInto sets into (a pointer to an argument) to the value at path of an earlier result.
func refInto(t *testing.T, scenario string, seq int, from any, path string, into any) {
	t.Helper()
	v, err := pathValue(from, path)
	if err != nil {
		t.Fatalf("%s step %d: ref: %v", scenario, seq, err)
	}
	raw, err := json.Marshal(v)
	if err != nil {
		t.Fatalf("%s step %d: ref %q: %v", scenario, seq, path, err)
	}
	if err := json.Unmarshal(raw, into); err != nil {
		t.Fatalf("%s step %d: ref %q does not fit its argument: %v", scenario, seq, path, err)
	}
}

// threadRef returns the JSON object args with member name set to the value at path of an earlier result.
func threadRef(t *testing.T, scenario string, seq int, args, name string, from any, path string) string {
	t.Helper()
	v, err := pathValue(from, path)
	if err != nil {
		t.Fatalf("%s step %d: ref: %v", scenario, seq, err)
	}
	fields := map[string]any{}
	if err := json.Unmarshal([]byte(args), &fields); err != nil {
		t.Fatalf("%s step %d: arguments %s: %v", scenario, seq, args, err)
	}
	fields[name] = v
	raw, err := json.Marshal(fields)
	if err != nil {
		t.Fatalf("%s step %d: arguments: %v", scenario, seq, err)
	}
	return string(raw)
}

`

// layerErrorHasCode is a layer component's code match: %[1]s is the layer
// package alias whose typed Error carries the kind.
const layerErrorHasCode = `// errorHasCode matches the layer error's kind name, or the code as a substring
// of the error text for a component-specific code.
func errorHasCode(err error, code string) bool {
	var le *%[1]s.Error
	if errors.As(err, &le) && le.Kind.String() == code {
		return true
	}
	return strings.Contains(err.Error(), code)
}

`

// matchHelpers is the JSON-subset comparison expect uses; no format verbs.
const matchHelpers = `// resultMatches decodes the expectation (a JSON document, or a bare string)
// and the marshalled outcome, and compares them as a subset.
func resultMatches(wantRaw string, got any) bool {
	var want any
	if json.Unmarshal([]byte(wantRaw), &want) != nil {
		want = wantRaw
	}
	raw, err := json.Marshal(got)
	if err != nil {
		return false
	}
	var g any
	if json.Unmarshal(raw, &g) != nil {
		return false
	}
	return subset(want, g)
}

// subset: every key of an expected object is present and matches; an expected
// array matches element-wise; a scalar must be equal.
func subset(want, got any) bool {
	switch w := want.(type) {
	case map[string]any:
		g, ok := got.(map[string]any)
		if !ok {
			return false
		}
		for k, wv := range w {
			gv, ok := g[k]
			if !ok || !subset(wv, gv) {
				return false
			}
		}
		return true
	case []any:
		g, ok := got.([]any)
		if !ok || len(g) != len(w) {
			return false
		}
		for i := range w {
			if !subset(w[i], g[i]) {
				return false
			}
		}
		return true
	default:
		return reflect.DeepEqual(want, got)
	}
}
`
