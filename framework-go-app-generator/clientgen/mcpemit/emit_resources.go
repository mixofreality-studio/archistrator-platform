package mcpemit

import (
	"errors"
	"fmt"
	"go/format"
	"strings"
)

// ResourceMIMEType is the MIME type an MCP Apps host requires of a ui:// resource (ext-apps'
// RESOURCE_MIME_TYPE).
const ResourceMIMEType = "text/html;profile=mcp-app"

// ResourceURI is the ui:// resource of one mcpApp Client's UI bundle. Every operation the Client
// reaches names it in its tool's _meta.ui.resourceUri.
func ResourceURI(app, surface string) string {
	return "ui://" + app + "/" + surface + "/shell.html"
}

// ResourceCSP is the Content-Security-Policy metadata of every generated resource: the bundle is one
// self-contained file that calls only through the host bridge, so it declares no origin to connect
// to and none to load resources from.
func ResourceCSP() map[string]any {
	return map[string]any{"connectDomains": []string{}, "resourceDomains": []string{}}
}

// ResourceOptions configures GenerateResources.
type ResourceOptions struct {
	Package  string   // the composition root's package ("main")
	App      string   // the app's name in the resource URIs
	Surfaces []string // the built mcpApp Client ids, sorted
}

// GenerateResources renders mcpapps.gen.go: registerMCPAppResources, which adds one resource per
// surface to the composed /mcp server. A resource's handler reads <webDistDir>/<surface>/shell.html
// at read time and answers it as one text content with the MCP Apps MIME type; an empty webDistDir
// or a missing file is a resource-not-found error.
func GenerateResources(o ResourceOptions) ([]byte, error) {
	if o.Package == "" || o.App == "" {
		return nil, errors.New("mcpemit: GenerateResources needs a Package and an App")
	}
	if len(o.Surfaces) == 0 {
		return nil, errors.New("mcpemit: GenerateResources needs at least one surface")
	}
	var b strings.Builder
	b.WriteString("// Code generated by appgen compose (mcpemit). DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", o.Package)
	b.WriteString("import (\n\t\"context\"\n\t\"errors\"\n\t\"io/fs\"\n\t\"os\"\n\t\"path/filepath\"\n\n\t\"github.com/modelcontextprotocol/go-sdk/mcp\"\n)\n\n")
	b.WriteString("// registerMCPAppResources adds the ui:// resource of every mcpApp Client to srv. Each is read from\n")
	b.WriteString("// the client's built bundle in the web dist at read time, with the MCP Apps MIME type and a CSP that\n")
	b.WriteString("// allows no origin: the bundle is one self-contained file that calls only through the host bridge.\n")
	b.WriteString("func registerMCPAppResources(srv *mcp.Server, webDistDir string) {\n")
	for _, s := range o.Surfaces {
		uri := ResourceURI(o.App, s)
		fmt.Fprintf(&b, "\tsrv.AddResource(&mcp.Resource{\n\t\tURI: %q, Name: %q, MIMEType: %q,\n", uri, s, ResourceMIMEType)
		b.WriteString("\t\tMeta: mcp.Meta{\"ui\": map[string]any{\"csp\": map[string]any{\"connectDomains\": []string{}, \"resourceDomains\": []string{}}}},\n")
		fmt.Fprintf(&b, "\t}, func(_ context.Context, _ *mcp.ReadResourceRequest) (*mcp.ReadResourceResult, error) {\n\t\treturn readMCPAppShell(%q, webDistDir, filepath.Join(webDistDir, %q, \"shell.html\"))\n\t})\n", uri, s)
	}
	b.WriteString("}\n\n")
	b.WriteString("// readMCPAppShell answers one bundle file as the resource uri; an unset dist or a missing file is\n")
	b.WriteString("// the SDK's resource-not-found error.\n")
	b.WriteString("func readMCPAppShell(uri, webDistDir, file string) (*mcp.ReadResourceResult, error) {\n")
	b.WriteString("\tif webDistDir == \"\" {\n\t\treturn nil, mcp.ResourceNotFoundError(uri)\n\t}\n")
	b.WriteString("\ttext, err := os.ReadFile(file)\n")
	b.WriteString("\tif errors.Is(err, fs.ErrNotExist) {\n\t\treturn nil, mcp.ResourceNotFoundError(uri)\n\t}\n")
	b.WriteString("\tif err != nil {\n\t\treturn nil, err\n\t}\n")
	fmt.Fprintf(&b, "\treturn &mcp.ReadResourceResult{Contents: []*mcp.ResourceContents{{URI: uri, MIMEType: %q, Text: string(text)}}}, nil\n}\n", ResourceMIMEType)
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("mcpemit: format the resources: %w\n%s", err, b.String())
	}
	return src, nil
}
